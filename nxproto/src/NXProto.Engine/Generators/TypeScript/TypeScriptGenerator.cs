using System.Text;
using NXProto.Core.Constants;
using NXProto.Core.Contracts;
using NXProto.Core.Models;

namespace NXProto.Engine.Generators.TypeScript;

/// <summary>
/// Code generator for TypeScript packet classes with binary Little-Endian DataView serialization/deserialization.
/// Seamlessly integrates with @ppnsys/nalix-sdk (NalixClient / WebSocketSession).
/// </summary>
public sealed class TypeScriptGenerator : ICodeGenerator
{
    public string LanguageName => "TypeScript";

    public IReadOnlyList<GeneratedFile> Generate(IReadOnlyList<PacketSchema> packets)
    {
        PacketSchema? headerSchema = packets.FirstOrDefault(p => p.Name == ProtocolConstants.PacketHeaderName);
        List<PacketSchema> nonHeaderPackets = [.. packets.Where(p => p.Name != ProtocolConstants.PacketHeaderName)];

        string main = GenerateMain(headerSchema, nonHeaderPackets);
        string tests = GenerateTests(nonHeaderPackets);

        return
        [
            new GeneratedFile("packets.ts", main, "src/"),
            new GeneratedFile("packets.test.ts", tests, "tests/")
        ];
    }

    private static string GenerateMain(PacketSchema? headerSchema, IReadOnlyList<PacketSchema> nonHeaderPackets)
    {
        StringBuilder sb = new(65536);

        _ = sb.AppendLine("// <auto-generated/>");
        _ = sb.AppendLine("// Generated by Protogen — TypeScriptGenerator");
        _ = sb.AppendLine("// DO NOT EDIT MANUALLY");
        _ = sb.AppendLine();
        _ = sb.AppendLine("export const NALIX_HEADER_SIZE = 6;");
        _ = sb.AppendLine();

        GenerateDefaultHeaderClass(sb);

        foreach (PacketSchema packet in nonHeaderPackets)
        {
            GeneratePacketClass(sb, packet);
        }

        return sb.ToString();
    }

    private static void GenerateDefaultHeaderClass(StringBuilder sb)
    {
        _ = sb.AppendLine("/**");
        _ = sb.AppendLine(" * Common Nalix v14 6-byte packet header (Little-Endian).");
        _ = sb.AppendLine(" */");
        _ = sb.AppendLine("export class PacketHeader {");
        _ = sb.AppendLine("  public opcode: number;");
        _ = sb.AppendLine("  public flags: number;");
        _ = sb.AppendLine("  public priority: number;");
        _ = sb.AppendLine("  public sequenceId: number;");
        _ = sb.AppendLine();
        _ = sb.AppendLine("  constructor(opcode: number = 0, flags: number = 0, priority: number = 0, sequenceId: number = 0) {");
        _ = sb.AppendLine("    this.opcode = opcode & 0xffff;");
        _ = sb.AppendLine("    this.flags = flags & 0xff;");
        _ = sb.AppendLine("    this.priority = priority & 0xff;");
        _ = sb.AppendLine("    this.sequenceId = sequenceId & 0xffff;");
        _ = sb.AppendLine("  }");
        _ = sb.AppendLine();
        _ = sb.AppendLine("  public encode(dst: Uint8Array, offset: number = 0): void {");
        _ = sb.AppendLine("    const view = new DataView(dst.buffer, dst.byteOffset + offset, 6);");
        _ = sb.AppendLine("    view.setUint16(0, this.opcode, true);");
        _ = sb.AppendLine("    view.setUint8(2, this.flags);");
        _ = sb.AppendLine("    view.setUint8(3, this.priority);");
        _ = sb.AppendLine("    view.setUint16(4, this.sequenceId, true);");
        _ = sb.AppendLine("  }");
        _ = sb.AppendLine();
        _ = sb.AppendLine("  public static decode(src: Uint8Array, offset: number = 0): PacketHeader {");
        _ = sb.AppendLine("    const view = new DataView(src.buffer, src.byteOffset + offset, 6);");
        _ = sb.AppendLine("    const opcode = view.getUint16(0, true);");
        _ = sb.AppendLine("    const flags = view.getUint8(2);");
        _ = sb.AppendLine("    const priority = view.getUint8(3);");
        _ = sb.AppendLine("    const sequenceId = view.getUint16(4, true);");
        _ = sb.AppendLine("    return new PacketHeader(opcode, flags, priority, sequenceId);");
        _ = sb.AppendLine("  }");
        _ = sb.AppendLine("}");
        _ = sb.AppendLine();
    }

    private static void GeneratePacketClass(StringBuilder sb, PacketSchema packet)
    {
        string name = packet.Name;
        int fixedSize = CalculateFixedSize(packet);

        _ = sb.AppendLine("/**");
        AppendInvariant(sb, $" * {name} — OpCode: 0x{packet.OpCode:X4}, Fixed Size: {fixedSize} bytes.");
        _ = sb.AppendLine(" */");
        AppendInvariant(sb, $"export class {name} {{");
        AppendInvariant(sb, $"  public static readonly OPCODE: number = 0x{packet.OpCode:X4};");
        AppendInvariant(sb, $"  public static readonly FIXED_SIZE: number = {fixedSize};");
        _ = sb.AppendLine();

        foreach (FieldSchema f in packet.Fields)
        {
            string tsType = GetTsType(f);
            string propName = ToCamelCase(f.Name);
            string defaultVal = GetDefaultValue(f);
            AppendInvariant(sb, $"  public {propName}: {tsType} = {defaultVal};");
        }

        _ = sb.AppendLine();

        // encode() method
        _ = sb.AppendLine("  public encode(): Uint8Array {");

        // Per-field pre-encoding lives in the method scope so the size pass and the write pass both see it.
        foreach (FieldSchema f in packet.Fields)
        {
            string c = ToCamelCase(f.Name);
            if (IsStringField(f))
            {
                AppendInvariant(sb, $"    const {c}Bytes = new TextEncoder().encode(this.{c});");
            }
            else if (IsArrayField(f) && GetArrayElementKind(f) == ArrayElementKind.String)
            {
                AppendInvariant(sb, $"    const {c}Items = this.{c}.map((s) => new TextEncoder().encode(s));");
            }
        }

        if (packet.HasVariableFields)
        {
            AppendInvariant(sb, $"    let totalSize = {name}.FIXED_SIZE;");
            foreach (FieldSchema f in packet.Fields)
            {
                string c = ToCamelCase(f.Name);
                string prop = $"this.{c}";
                if (IsStringField(f))
                {
                    AppendInvariant(sb, $"    totalSize += 4 + {c}Bytes.byteLength;");
                }
                else if (IsDynamicBytesField(f))
                {
                    AppendInvariant(sb, $"    totalSize += 4 + {prop}.byteLength;");
                }
                else if (IsArrayField(f))
                {
                    ArrayElementKind kind = GetArrayElementKind(f);
                    if (kind == ArrayElementKind.String)
                    {
                        AppendInvariant(sb, $"    totalSize += 4 + {c}Items.reduce((n, b) => n + 4 + b.byteLength, 0);");
                    }
                    else
                    {
                        AppendInvariant(sb, $"    totalSize += 4 + ({prop}.length * {ArrayElementWireSize(kind)});");
                    }
                }
            }
            _ = sb.AppendLine("    const buffer = new Uint8Array(totalSize);");
        }
        else
        {
            AppendInvariant(sb, $"    const buffer = new Uint8Array({name}.FIXED_SIZE);");
        }

        _ = sb.AppendLine("    const view = new DataView(buffer.buffer, buffer.byteOffset, buffer.byteLength);");
        _ = sb.AppendLine("    let offset = 0;");

        foreach (FieldSchema f in packet.Fields)
        {
            WriteEncodeField(sb, f);
        }

        _ = sb.AppendLine("    return buffer;");
        _ = sb.AppendLine("  }");
        _ = sb.AppendLine();

        // decode() method
        AppendInvariant(sb, $"  public static decode(raw: Uint8Array | ArrayBuffer): {name} {{");
        _ = sb.AppendLine("    const buffer = raw instanceof Uint8Array ? raw : new Uint8Array(raw);");
        AppendInvariant(sb, $"    if (buffer.byteLength < {name}.FIXED_SIZE) {{");
        AppendInvariant(sb, $"      throw new Error(`Buffer too small for {name}: expected at least ${{ {name}.FIXED_SIZE }} bytes, got ${{buffer.byteLength}}`);");
        _ = sb.AppendLine("    }");
        _ = sb.AppendLine("    const view = new DataView(buffer.buffer, buffer.byteOffset, buffer.byteLength);");
        _ = sb.AppendLine("    let offset = 0;");
        AppendInvariant(sb, $"    const pkt = new {name}();");

        foreach (FieldSchema f in packet.Fields)
        {
            WriteDecodeField(sb, f);
        }

        _ = sb.AppendLine("    return pkt;");
        _ = sb.AppendLine("  }");
        _ = sb.AppendLine("}");
        _ = sb.AppendLine();
    }

    private static void WriteEncodeField(StringBuilder sb, FieldSchema f)
    {
        string prop = $"this.{ToCamelCase(f.Name)}";

        if (f.IsNullable)
        {
            AppendInvariant(sb, $"    if ({prop} != null) {{");
            _ = sb.AppendLine("      view.setUint8(offset++, 1);");
        }

        string val = prop;

        if (f.IsHeader || f.CSharpType.Contains(ProtocolConstants.PacketHeaderName, StringComparison.Ordinal))
        {
            AppendInvariant(sb, $"    {val}.encode(buffer, offset);");
            _ = sb.AppendLine("    offset += 6;");
        }
        else if (IsStringField(f))
        {
            string bytesVar = $"{ToCamelCase(f.Name)}Bytes";
            AppendInvariant(sb, $"    view.setInt32(offset, {bytesVar}.byteLength, true);");
            _ = sb.AppendLine("    offset += 4;");
            AppendInvariant(sb, $"    buffer.set({bytesVar}, offset);");
            AppendInvariant(sb, $"    offset += {bytesVar}.byteLength;");
        }
        else if (IsArrayField(f))
        {
            WriteEncodeArray(sb, f);
        }
        else if (IsFixedByteArray(f))
        {
            AppendInvariant(sb, $"    buffer.set({val}, offset);");
            AppendInvariant(sb, $"    offset += {f.Size};");
        }
        else if (IsDynamicBytesField(f))
        {
            AppendInvariant(sb, $"    view.setInt32(offset, {val}.byteLength, true);");
            _ = sb.AppendLine("    offset += 4;");
            AppendInvariant(sb, $"    buffer.set({val}, offset);");
            AppendInvariant(sb, $"    offset += {val}.byteLength;");
        }
        else
        {
            switch (f.CType)
            {
                case "uint8_t":
                    if (f.CSharpType is "bool" or "System.Boolean")
                    {
                        AppendInvariant(sb, $"    view.setUint8(offset++, {val} ? 1 : 0);");
                    }
                    else
                    {
                        AppendInvariant(sb, $"    view.setUint8(offset++, {val});");
                    }
                    break;
                case "int8_t":
                    AppendInvariant(sb, $"    view.setInt8(offset++, {val});");
                    break;
                case "uint16_t":
                    AppendInvariant(sb, $"    view.setUint16(offset, {val}, true);");
                    _ = sb.AppendLine("    offset += 2;");
                    break;
                case "int16_t":
                    AppendInvariant(sb, $"    view.setInt16(offset, {val}, true);");
                    _ = sb.AppendLine("    offset += 2;");
                    break;
                case "uint32_t":
                    AppendInvariant(sb, $"    view.setUint32(offset, {val}, true);");
                    _ = sb.AppendLine("    offset += 4;");
                    break;
                case "int32_t":
                    AppendInvariant(sb, $"    view.setInt32(offset, {val}, true);");
                    _ = sb.AppendLine("    offset += 4;");
                    break;
                case "float":
                    AppendInvariant(sb, $"    view.setFloat32(offset, {val}, true);");
                    _ = sb.AppendLine("    offset += 4;");
                    break;
                case "double":
                    AppendInvariant(sb, $"    view.setFloat64(offset, {val}, true);");
                    _ = sb.AppendLine("    offset += 8;");
                    break;
                case "uint64_t":
                    AppendInvariant(sb, $"    view.setBigUint64(offset, BigInt({val}), true);");
                    _ = sb.AppendLine("    offset += 8;");
                    break;
                case "int64_t":
                    AppendInvariant(sb, $"    view.setBigInt64(offset, BigInt({val}), true);");
                    _ = sb.AppendLine("    offset += 8;");
                    break;
                default:
                    if (f.Size == 16)
                    {
                        AppendInvariant(sb, $"    buffer.set({val}, offset);");
                        _ = sb.AppendLine("    offset += 16;");
                    }
                    else if (f.Size > 0)
                    {
                        AppendInvariant(sb, $"    buffer.set({val}, offset);");
                        AppendInvariant(sb, $"    offset += {f.Size};");
                    }
                    break;
            }
        }

        if (f.IsNullable)
        {
            _ = sb.AppendLine("    } else {");
            _ = sb.AppendLine("      view.setUint8(offset++, 0);");
            _ = sb.AppendLine("    }");
        }
    }

    private static void WriteDecodeField(StringBuilder sb, FieldSchema f)
    {
        string prop = $"pkt.{ToCamelCase(f.Name)}";

        if (f.IsNullable)
        {
            _ = sb.AppendLine("    if (view.getUint8(offset++) === 1) {");
        }

        if (f.IsHeader || f.CSharpType.Contains(ProtocolConstants.PacketHeaderName, StringComparison.Ordinal))
        {
            AppendInvariant(sb, $"    {prop} = PacketHeader.decode(buffer, offset);");
            _ = sb.AppendLine("    offset += 6;");
        }
        else if (IsStringField(f))
        {
            AppendInvariant(sb, $"    const {ToCamelCase(f.Name)}Len = view.getInt32(offset, true);");
            _ = sb.AppendLine("    offset += 4;");
            AppendInvariant(sb, $"    {prop} = {ToCamelCase(f.Name)}Len > 0 ? new TextDecoder().decode(buffer.subarray(offset, offset + {ToCamelCase(f.Name)}Len)) : \"\";");
            AppendInvariant(sb, $"    offset += {ToCamelCase(f.Name)}Len;");
        }
        else if (IsArrayField(f))
        {
            WriteDecodeArray(sb, f);
        }
        else if (IsFixedByteArray(f))
        {
            AppendInvariant(sb, $"    {prop} = buffer.slice(offset, offset + {f.Size});");
            AppendInvariant(sb, $"    offset += {f.Size};");
        }
        else if (IsDynamicBytesField(f))
        {
            AppendInvariant(sb, $"    const {ToCamelCase(f.Name)}Len = view.getInt32(offset, true);");
            _ = sb.AppendLine("    offset += 4;");
            AppendInvariant(sb, $"    {prop} = buffer.slice(offset, offset + {ToCamelCase(f.Name)}Len);");
            AppendInvariant(sb, $"    offset += {ToCamelCase(f.Name)}Len;");
        }
        else
        {
            switch (f.CType)
            {
                case "uint8_t":
                    if (f.CSharpType is "bool" or "System.Boolean")
                    {
                        AppendInvariant(sb, $"    {prop} = view.getUint8(offset++) !== 0;");
                    }
                    else
                    {
                        AppendInvariant(sb, $"    {prop} = view.getUint8(offset++);");
                    }
                    break;
                case "int8_t":
                    AppendInvariant(sb, $"    {prop} = view.getInt8(offset++);");
                    break;
                case "uint16_t":
                    AppendInvariant(sb, $"    {prop} = view.getUint16(offset, true);");
                    _ = sb.AppendLine("    offset += 2;");
                    break;
                case "int16_t":
                    AppendInvariant(sb, $"    {prop} = view.getInt16(offset, true);");
                    _ = sb.AppendLine("    offset += 2;");
                    break;
                case "uint32_t":
                    AppendInvariant(sb, $"    {prop} = view.getUint32(offset, true);");
                    _ = sb.AppendLine("    offset += 4;");
                    break;
                case "int32_t":
                    AppendInvariant(sb, $"    {prop} = view.getInt32(offset, true);");
                    _ = sb.AppendLine("    offset += 4;");
                    break;
                case "float":
                    AppendInvariant(sb, $"    {prop} = view.getFloat32(offset, true);");
                    _ = sb.AppendLine("    offset += 4;");
                    break;
                case "double":
                    AppendInvariant(sb, $"    {prop} = view.getFloat64(offset, true);");
                    _ = sb.AppendLine("    offset += 8;");
                    break;
                case "uint64_t":
                    AppendInvariant(sb, $"    {prop} = view.getBigUint64(offset, true);");
                    _ = sb.AppendLine("    offset += 8;");
                    break;
                case "int64_t":
                    AppendInvariant(sb, $"    {prop} = view.getBigInt64(offset, true);");
                    _ = sb.AppendLine("    offset += 8;");
                    break;
                default:
                    if (f.Size == 16)
                    {
                        AppendInvariant(sb, $"    {prop} = buffer.slice(offset, offset + 16);");
                        _ = sb.AppendLine("    offset += 16;");
                    }
                    else if (f.Size > 0)
                    {
                        AppendInvariant(sb, $"    {prop} = buffer.slice(offset, offset + {f.Size});");
                        AppendInvariant(sb, $"    offset += {f.Size};");
                    }
                    break;
            }
        }

        if (f.IsNullable)
        {
            _ = sb.AppendLine("    } else {");
            AppendInvariant(sb, $"      {prop} = null;");
            _ = sb.AppendLine("    }");
        }
    }

    private static string GenerateTests(IReadOnlyList<PacketSchema> packets)
    {
        StringBuilder sb = new(16384);

        _ = sb.AppendLine("// <auto-generated/>");
        _ = sb.AppendLine("// Round-trip serialization tests for Nalix TypeScript packets");
        _ = sb.AppendLine();
        _ = sb.AppendLine("import { test } from 'node:test';");
        _ = sb.AppendLine("import assert from 'node:assert/strict';");
        _ = sb.AppendLine("import * as P from '../src/packets.js';");
        _ = sb.AppendLine();

        foreach (PacketSchema packet in packets)
        {
            string name = packet.Name;
            AppendInvariant(sb, $"test('{name} round-trip binary serialization', () => {{");
            AppendInvariant(sb, $"  const pkt = new P.{name}();");

            foreach (FieldSchema f in packet.Fields)
            {
                if (f.IsHeader || f.CSharpType.Contains(ProtocolConstants.PacketHeaderName, StringComparison.Ordinal))
                {
                    AppendInvariant(sb, $"  pkt.{ToCamelCase(f.Name)}.opcode = P.{name}.OPCODE;");
                    AppendInvariant(sb, $"  pkt.{ToCamelCase(f.Name)}.sequenceId = 42;");
                }
                else if (IsStringField(f))
                {
                    AppendInvariant(sb, $"  pkt.{ToCamelCase(f.Name)} = 'test-string-payload';");
                }
                else if (IsFixedByteArray(f))
                {
                    AppendInvariant(sb, $"  pkt.{ToCamelCase(f.Name)}.fill(0x5a);");
                }
                else if (IsDynamicBytesField(f))
                {
                    AppendInvariant(sb, $"  pkt.{ToCamelCase(f.Name)} = new Uint8Array([1, 2, 3, 0xfe]);");
                }
                else if (IsArrayField(f))
                {
                    AppendInvariant(sb, $"  pkt.{ToCamelCase(f.Name)} = {ArrayTestSample(GetArrayElementKind(f))};");
                }
                else if (f.CSharpType is "bool" or "System.Boolean")
                {
                    AppendInvariant(sb, $"  pkt.{ToCamelCase(f.Name)} = true;");
                }
                else if (f.CType is "int64_t" or "uint64_t")
                {
                    AppendInvariant(sb, $"  pkt.{ToCamelCase(f.Name)} = 123456789012345678n;");
                }
                else
                {
                    AppendInvariant(sb, $"  pkt.{ToCamelCase(f.Name)} = 42;");
                }
            }

            _ = sb.AppendLine("  const encoded = pkt.encode();");
            AppendInvariant(sb, $"  assert.ok(encoded.byteLength >= P.{name}.FIXED_SIZE);");
            AppendInvariant(sb, $"  const decoded = P.{name}.decode(encoded);");

            foreach (FieldSchema f in packet.Fields)
            {
                string prop = ToCamelCase(f.Name);
                if (f.IsHeader || f.CSharpType.Contains(ProtocolConstants.PacketHeaderName, StringComparison.Ordinal))
                {
                    AppendInvariant(sb, $"  assert.equal(decoded.{prop}.opcode, P.{name}.OPCODE);");
                    AppendInvariant(sb, $"  assert.equal(decoded.{prop}.sequenceId, 42);");
                }
                else if (IsFixedByteArray(f) || IsDynamicBytesField(f) || IsArrayField(f))
                {
                    AppendInvariant(sb, $"  assert.deepEqual(decoded.{prop}, pkt.{prop});");
                }
                else
                {
                    AppendInvariant(sb, $"  assert.equal(decoded.{prop}, pkt.{prop});");
                }
            }

            _ = sb.AppendLine("});");
            _ = sb.AppendLine();
        }

        return sb.ToString();
    }

    private static string GetTsType(FieldSchema f)
    {
        string baseType;

        if (f.IsHeader || f.CSharpType.Contains(ProtocolConstants.PacketHeaderName, StringComparison.Ordinal))
        {
            baseType = "PacketHeader";
        }
        else if (IsStringField(f))
        {
            baseType = "string";
        }
        else if (IsFixedByteArray(f) || IsDynamicBytesField(f))
        {
            baseType = "Uint8Array";
        }
        else if (IsArrayField(f))
        {
            baseType = $"{ArrayElementTsType(GetArrayElementKind(f))}[]";
        }
        else if (f.CSharpType is "bool" or "System.Boolean")
        {
            baseType = "boolean";
        }
        else if (f.CType is "int64_t" or "uint64_t")
        {
            baseType = "bigint";
        }
        else
        {
            baseType = "number";
        }

        return f.IsNullable ? $"{baseType} | null" : baseType;
    }

    private static string GetDefaultValue(FieldSchema f)
    {
        if (f.IsNullable)
        {
            return "null";
        }

        if (f.IsHeader || f.CSharpType.Contains(ProtocolConstants.PacketHeaderName, StringComparison.Ordinal))
        {
            return "new PacketHeader()";
        }

        if (IsStringField(f))
        {
            return "\"\"";
        }

        if (IsFixedByteArray(f))
        {
            return $"new Uint8Array({f.Size})";
        }

        if (IsDynamicBytesField(f))
        {
            return "new Uint8Array(0)";
        }

        if (IsArrayField(f))
        {
            return "[]";
        }

        if (f.CSharpType is "bool" or "System.Boolean")
        {
            return "false";
        }

        if (f.CType is "int64_t" or "uint64_t")
        {
            return "0n";
        }

        return "0";
    }

    private static bool IsStringField(FieldSchema f) =>
        f.CSharpType is "string" or "System.String" ||
        (f.CType == ProtocolConstants.StringCType && !IsByteArrayField(f) && !IsArrayField(f));

    private static bool IsFixedByteArray(FieldSchema f) =>
        f.CSharpType == ProtocolConstants.Bytes32FullName ||
        f.RustType.StartsWith("[u8; ", StringComparison.Ordinal) ||
        (f.Size > 8 && f.CType != ProtocolConstants.StringCType);

    // byte[] is a length-prefixed raw payload: [int32 length][bytes] -> Uint8Array.
    private static bool IsByteArrayField(FieldSchema f) =>
        f.CSharpType is "byte[]" or "System.Byte[]";

    private static bool IsDynamicBytesField(FieldSchema f) =>
        IsByteArrayField(f) ||
        (f.RustType == "Vec<u8>" && f.CType != ProtocolConstants.StringCType && !IsArrayField(f));

    // Any other array or generic list: [int32 count][count elements], see docs/SPECIFICATION.md §2.5.2.
    private static bool IsArrayField(FieldSchema f) =>
        !IsByteArrayField(f) && GetCollectionElementType(f.CSharpType) is not null;

    private static readonly string[] GenericCollectionPrefixes =
    [
        "System.Collections.Generic.List<",
        "System.Collections.Generic.IList<",
        "System.Collections.Generic.IReadOnlyList<",
        "System.Collections.Generic.HashSet<",
        "List<",
        "IList<",
        "IReadOnlyList<",
        "HashSet<",
    ];

    private static string? GetCollectionElementType(string csharpType)
    {
        if (csharpType.EndsWith("[]", StringComparison.Ordinal))
        {
            return csharpType[..^2];
        }

        foreach (string prefix in GenericCollectionPrefixes)
        {
            if (csharpType.StartsWith(prefix, StringComparison.Ordinal) && csharpType.EndsWith('>'))
            {
                return csharpType[prefix.Length..^1];
            }
        }

        return null;
    }

    private enum ArrayElementKind
    {
        Int8,
        UInt8,
        Bool,
        Int16,
        UInt16,
        Int32,
        UInt32,
        Float32,
        Float64,
        Int64,
        UInt64,
        Guid16,
        String,
    }

    /// <summary>
    /// Resolves the wire layout of one array element. C# names are checked first so that
    /// <c>Guid</c> (C-side <c>ByteArray</c>) and <c>bool</c> are not confused with byte elements.
    /// </summary>
    private static ArrayElementKind GetArrayElementKind(FieldSchema f)
    {
        string elem = GetCollectionElementType(f.CSharpType)
            ?? throw new InvalidOperationException($"Field '{f.Name}' is not an array or collection.");

        switch (elem)
        {
            case "string" or "System.String":
                return ArrayElementKind.String;
            case "System.Guid" or "Guid":
                return ArrayElementKind.Guid16;
            case "bool" or "System.Boolean":
                return ArrayElementKind.Bool;
            case "sbyte" or "System.SByte":
                return ArrayElementKind.Int8;
            case "byte" or "System.Byte":
                return ArrayElementKind.UInt8;
            case "short" or "System.Int16":
                return ArrayElementKind.Int16;
            case "ushort" or "System.UInt16" or "char" or "System.Char":
                return ArrayElementKind.UInt16;
            case "int" or "System.Int32":
                return ArrayElementKind.Int32;
            case "uint" or "System.UInt32":
                return ArrayElementKind.UInt32;
            case "float" or "System.Single":
                return ArrayElementKind.Float32;
            case "double" or "System.Double":
                return ArrayElementKind.Float64;
            case "long" or "System.Int64":
                return ArrayElementKind.Int64;
            case "ulong" or "System.UInt64":
                return ArrayElementKind.UInt64;
        }

        // Enums and other element types: fall back to the C element layout chosen by TypeResolver.
        return f.CType switch
        {
            "StringArray" => ArrayElementKind.String,
            "Int8Array" => ArrayElementKind.Int8,
            "ByteArray" => ArrayElementKind.UInt8,
            "Int16Array" => ArrayElementKind.Int16,
            "UInt16Array" => ArrayElementKind.UInt16,
            "Int32Array" => ArrayElementKind.Int32,
            "UInt32Array" => ArrayElementKind.UInt32,
            "FloatArray" => ArrayElementKind.Float32,
            "DoubleArray" => ArrayElementKind.Float64,
            "Int64Array" => ArrayElementKind.Int64,
            "UInt64Array" => ArrayElementKind.UInt64,
            _ => throw new NotSupportedException(
                $"TypeScript generator: unsupported array element type '{elem}' for field '{f.Name}'."),
        };
    }

    private static string ArrayElementTsType(ArrayElementKind kind) => kind switch
    {
        ArrayElementKind.Bool => "boolean",
        ArrayElementKind.Int64 or ArrayElementKind.UInt64 => "bigint",
        ArrayElementKind.String => "string",
        ArrayElementKind.Guid16 => "Uint8Array",
        _ => "number",
    };

    private static int ArrayElementWireSize(ArrayElementKind kind) => kind switch
    {
        ArrayElementKind.Int8 or ArrayElementKind.UInt8 or ArrayElementKind.Bool => 1,
        ArrayElementKind.Int16 or ArrayElementKind.UInt16 => 2,
        ArrayElementKind.Int32 or ArrayElementKind.UInt32 or ArrayElementKind.Float32 => 4,
        ArrayElementKind.Int64 or ArrayElementKind.UInt64 or ArrayElementKind.Float64 => 8,
        ArrayElementKind.Guid16 => 16,
        _ => 0,
    };

    private static string ArrayElementWriteStatement(ArrayElementKind kind) => kind switch
    {
        ArrayElementKind.Int8 => "view.setInt8(offset++, item);",
        ArrayElementKind.UInt8 => "view.setUint8(offset++, item);",
        ArrayElementKind.Bool => "view.setUint8(offset++, item ? 1 : 0);",
        ArrayElementKind.Int16 => "view.setInt16(offset, item, true); offset += 2;",
        ArrayElementKind.UInt16 => "view.setUint16(offset, item, true); offset += 2;",
        ArrayElementKind.Int32 => "view.setInt32(offset, item, true); offset += 4;",
        ArrayElementKind.UInt32 => "view.setUint32(offset, item, true); offset += 4;",
        ArrayElementKind.Float32 => "view.setFloat32(offset, item, true); offset += 4;",
        ArrayElementKind.Float64 => "view.setFloat64(offset, item, true); offset += 8;",
        ArrayElementKind.Int64 => "view.setBigInt64(offset, BigInt(item), true); offset += 8;",
        ArrayElementKind.UInt64 => "view.setBigUint64(offset, BigInt(item), true); offset += 8;",
        ArrayElementKind.Guid16 => "buffer.set(item, offset); offset += 16;",
        _ => throw new InvalidOperationException("String elements are written through their encoded byte arrays."),
    };

    private static string ArrayElementReadExpression(ArrayElementKind kind) => kind switch
    {
        ArrayElementKind.Int8 => "view.getInt8(offset)",
        ArrayElementKind.UInt8 => "view.getUint8(offset)",
        ArrayElementKind.Bool => "view.getUint8(offset) !== 0",
        ArrayElementKind.Int16 => "view.getInt16(offset, true)",
        ArrayElementKind.UInt16 => "view.getUint16(offset, true)",
        ArrayElementKind.Int32 => "view.getInt32(offset, true)",
        ArrayElementKind.UInt32 => "view.getUint32(offset, true)",
        ArrayElementKind.Float32 => "view.getFloat32(offset, true)",
        ArrayElementKind.Float64 => "view.getFloat64(offset, true)",
        ArrayElementKind.Int64 => "view.getBigInt64(offset, true)",
        ArrayElementKind.UInt64 => "view.getBigUint64(offset, true)",
        ArrayElementKind.Guid16 => "buffer.slice(offset, offset + 16)",
        _ => throw new InvalidOperationException("String elements are read through their length prefix."),
    };

    private static void WriteEncodeArray(StringBuilder sb, FieldSchema f)
    {
        string c = ToCamelCase(f.Name);
        ArrayElementKind kind = GetArrayElementKind(f);

        if (kind == ArrayElementKind.String)
        {
            AppendInvariant(sb, $"    view.setInt32(offset, this.{c}.length, true);");
            _ = sb.AppendLine("    offset += 4;");
            AppendInvariant(sb, $"    for (const item of {c}Items) {{");
            _ = sb.AppendLine("      view.setInt32(offset, item.byteLength, true);");
            _ = sb.AppendLine("      offset += 4;");
            _ = sb.AppendLine("      buffer.set(item, offset);");
            _ = sb.AppendLine("      offset += item.byteLength;");
            _ = sb.AppendLine("    }");
            return;
        }

        AppendInvariant(sb, $"    view.setInt32(offset, this.{c}.length, true);");
        _ = sb.AppendLine("    offset += 4;");
        AppendInvariant(sb, $"    for (const item of this.{c}) {{");
        AppendInvariant(sb, $"      {ArrayElementWriteStatement(kind)}");
        _ = sb.AppendLine("    }");
    }

    private static void WriteDecodeArray(StringBuilder sb, FieldSchema f)
    {
        string c = ToCamelCase(f.Name);
        string arr = $"{c}Arr";
        ArrayElementKind kind = GetArrayElementKind(f);

        AppendInvariant(sb, $"    const {c}Count = Math.max(0, view.getInt32(offset, true));");
        _ = sb.AppendLine("    offset += 4;");
        AppendInvariant(sb, $"    const {arr}: {ArrayElementTsType(kind)}[] = [];");
        AppendInvariant(sb, $"    for (let i = 0; i < {c}Count; i++) {{");
        if (kind == ArrayElementKind.String)
        {
            _ = sb.AppendLine("      const itemLen = view.getInt32(offset, true);");
            _ = sb.AppendLine("      offset += 4;");
            AppendInvariant(sb, $"      {arr}.push(new TextDecoder().decode(buffer.subarray(offset, offset + itemLen)));");
            _ = sb.AppendLine("      offset += itemLen;");
        }
        else
        {
            AppendInvariant(sb, $"      {arr}.push({ArrayElementReadExpression(kind)});");
            AppendInvariant(sb, $"      offset += {ArrayElementWireSize(kind)};");
        }
        _ = sb.AppendLine("    }");
        AppendInvariant(sb, $"    pkt.{c} = {arr};");
    }

    private static string ArrayTestSample(ArrayElementKind kind) => kind switch
    {
        ArrayElementKind.String => "['test-string-payload']",
        ArrayElementKind.Guid16 => "[new Uint8Array(16).fill(0x5a)]",
        ArrayElementKind.Bool => "[true, false]",
        ArrayElementKind.Int64 or ArrayElementKind.UInt64 => "[123456789012345678n, 42n]",
        _ => "[42, 7]",
    };

    private static int CalculateFixedSize(PacketSchema packet)
    {
        int size = 0;
        foreach (FieldSchema f in packet.Fields)
        {
            if (f.IsNullable)
            {
                size += 1;
            }
            if (f.Size > 0)
            {
                size += f.Size;
            }
        }
        return size;
    }

    private static string ToCamelCase(string s)
    {
        if (string.IsNullOrEmpty(s)) return s;
        if (s.Length == 1) return s.ToLowerInvariant();
        return char.ToLowerInvariant(s[0]) + s.Substring(1);
    }

    private static void AppendInvariant(StringBuilder sb, FormattableString value) =>
        sb.AppendLine(FormattableString.Invariant(value));
}
