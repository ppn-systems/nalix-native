using System.Text;
using Protogen.Core.Constants;
using Protogen.Core.Contracts;
using Protogen.Core.Models;

namespace Protogen.Engine.Generators.C;

/// <summary>
/// Code generator for native C header and source files compatible with Nalix v14.
/// Cross-platform packed structures (MSVC, GCC for ESP-IDF, Clang).
/// </summary>
public sealed class CGenerator : ICodeGenerator
{
    public string LanguageName => "C";

    public IReadOnlyList<GeneratedFile> Generate(IReadOnlyList<PacketSchema> packets)
    {
        PacketSchema? headerSchema = packets.FirstOrDefault(p => p.Name == ProtocolConstants.PacketHeaderName);
        List<PacketSchema> nonHeaderPackets = [.. packets.Where(p => p.Name != ProtocolConstants.PacketHeaderName)];

        string header = GenerateHeader(headerSchema, nonHeaderPackets);
        string source = GenerateSource(nonHeaderPackets);
        string tests = GenerateTests(nonHeaderPackets);

        return
        [
            new GeneratedFile("packets.h", header, "include/"),
            new GeneratedFile("packets.c", source, "src/"),
            new GeneratedFile("packet_test.c", tests, "tests/")
        ];
    }

    private static string GenerateHeader(PacketSchema? headerSchema, IReadOnlyList<PacketSchema> nonHeaderPackets)
    {
        StringBuilder sb = new(32768);

        _ = sb.AppendLine("// <auto-generated/>");
        _ = sb.AppendLine("// Generated by Protogen — CGenerator");
        _ = sb.AppendLine("// DO NOT EDIT MANUALLY");
        _ = sb.AppendLine();
        _ = sb.AppendLine("#pragma once");
        _ = sb.AppendLine();
        _ = sb.AppendLine("#include <stdint.h>");
        _ = sb.AppendLine("#include <stddef.h>");
        _ = sb.AppendLine("#include <stdbool.h>");
        _ = sb.AppendLine("#include <string.h>");
        _ = sb.AppendLine();

        _ = sb.AppendLine("typedef struct { uint8_t data[16]; } Bytes16;");
        _ = sb.AppendLine("typedef struct { uint8_t data[32]; } Bytes32;");
        _ = sb.AppendLine("typedef struct { uint8_t data[64]; } Bytes64;");
        _ = sb.AppendLine("typedef struct { uint8_t data[16]; } Guid;");
        _ = sb.AppendLine("typedef struct { uint8_t data[16]; } Decimal;");
        _ = sb.AppendLine("typedef struct { int64_t date_time; int16_t offset_minutes; } DateTimeOffset;");
        _ = sb.AppendLine("#if defined(__GNUC__) || defined(__clang__)");
        _ = sb.AppendLine("    typedef __int128_t int128_t;");
        _ = sb.AppendLine("    typedef __uint128_t uint128_t;");
        _ = sb.AppendLine("#else");
        _ = sb.AppendLine("    typedef struct { uint8_t data[16]; } int128_t;");
        _ = sb.AppendLine("    typedef struct { uint8_t data[16]; } uint128_t;");
        _ = sb.AppendLine("#endif");
        _ = sb.AppendLine();
        _ = sb.AppendLine("// Length-prefixed UTF-8 string (matches Nalix codec wire format)");
        _ = sb.AppendLine("// null = length -1, empty = length 0, otherwise [int32_t length][utf8 bytes]");
        _ = sb.AppendLine("typedef struct { int32_t length; uint8_t* data; } NalixString;");
        _ = sb.AppendLine();
        _ = sb.AppendLine("// Dynamic arrays / collections (matches Nalix wire format [int32_t count][elements...])");
        _ = sb.AppendLine("typedef struct { int32_t count; uint8_t* data; } ByteArray;");
        _ = sb.AppendLine("typedef struct { int32_t count; int8_t* data; } Int8Array;");
        _ = sb.AppendLine("typedef struct { int32_t count; int16_t* data; } Int16Array;");
        _ = sb.AppendLine("typedef struct { int32_t count; uint16_t* data; } UInt16Array;");
        _ = sb.AppendLine("typedef struct { int32_t count; int32_t* data; } Int32Array;");
        _ = sb.AppendLine("typedef struct { int32_t count; uint32_t* data; } UInt32Array;");
        _ = sb.AppendLine("typedef struct { int32_t count; int64_t* data; } Int64Array;");
        _ = sb.AppendLine("typedef struct { int32_t count; uint64_t* data; } UInt64Array;");
        _ = sb.AppendLine("typedef struct { int32_t count; float* data; } FloatArray;");
        _ = sb.AppendLine("typedef struct { int32_t count; double* data; } DoubleArray;");
        _ = sb.AppendLine("typedef struct { int32_t count; NalixString* data; } StringArray;");
        _ = sb.AppendLine();
        AppendInvariant(sb, $"// Nalix v14 standard {ProtocolConstants.PacketHeaderSize}-byte packet header");
        AppendInvariant(sb, $"#define PACKET_HEADER_SIZE {ProtocolConstants.PacketHeaderSize}");
        _ = sb.AppendLine();

        if (headerSchema != null)
        {
            _ = sb.AppendLine("#if defined(_MSC_VER) || defined(__GNUC__) || defined(__clang__)");
            _ = sb.AppendLine("    #pragma pack(push, 1)");
            _ = sb.AppendLine("#endif");
            _ = sb.AppendLine();
            _ = sb.AppendLine("typedef struct {");
            foreach (FieldSchema f in headerSchema.Fields)
            {
                AppendInvariant(sb, $"    {f.CType} {f.Name};");
            }
            _ = sb.AppendLine("} PacketHeader;");
            _ = sb.AppendLine();
            _ = sb.AppendLine("#if defined(_MSC_VER) || defined(__GNUC__) || defined(__clang__)");
            _ = sb.AppendLine("    #pragma pack(pop)");
            _ = sb.AppendLine("#endif");
            _ = sb.AppendLine();
        }

        _ = sb.AppendLine("#ifdef __cplusplus");
        _ = sb.AppendLine("extern \"C\" {");
        _ = sb.AppendLine("#endif");
        _ = sb.AppendLine();
        _ = sb.AppendLine("void nalix_string_free(NalixString* s);");
        _ = sb.AppendLine("void string_array_free(StringArray* arr);");
        _ = sb.AppendLine("void byte_array_free(ByteArray* arr);");
        _ = sb.AppendLine("void int8_array_free(Int8Array* arr);");
        _ = sb.AppendLine("void int16_array_free(Int16Array* arr);");
        _ = sb.AppendLine("void uint16_array_free(UInt16Array* arr);");
        _ = sb.AppendLine("void int32_array_free(Int32Array* arr);");
        _ = sb.AppendLine("void uint32_array_free(UInt32Array* arr);");
        _ = sb.AppendLine("void int64_array_free(Int64Array* arr);");
        _ = sb.AppendLine("void uint64_array_free(UInt64Array* arr);");
        _ = sb.AppendLine("void float_array_free(FloatArray* arr);");
        _ = sb.AppendLine("void double_array_free(DoubleArray* arr);");
        _ = sb.AppendLine("size_t packet_header_serialize(const PacketHeader* header, uint8_t* buf, size_t buf_size);");
        _ = sb.AppendLine("size_t packet_header_deserialize(PacketHeader* header, const uint8_t* buf, size_t buf_size);");
        _ = sb.AppendLine();

        foreach (PacketSchema p in nonHeaderPackets)
        {
            int wireSize = p.CalculateWireSize();

            AppendInvariant(sb, $"// {p.Name} — {wireSize} bytes, opcode 0x{p.OpCode:X4}");
            AppendInvariant(sb, $"#define PACKET_{p.Name.ToUpperInvariant()}_OPCODE 0x{p.OpCode:X4}U");
            AppendInvariant(sb, $"#define {p.Name.ToUpperInvariant()}_SIZE {wireSize}");
            _ = sb.AppendLine();
            _ = sb.AppendLine("#if defined(_MSC_VER) || defined(__GNUC__) || defined(__clang__)");
            _ = sb.AppendLine("    #pragma pack(push, 1)");
            _ = sb.AppendLine("#endif");
            _ = sb.AppendLine();
            _ = sb.AppendLine("typedef struct {");
            foreach (FieldSchema f in p.Fields)
            {
                string cType = f.CSharpType.Contains(ProtocolConstants.PacketHeaderName, StringComparison.Ordinal) ? ProtocolConstants.PacketHeaderName : f.CType;
                if (f.IsNullable)
                {
                    AppendInvariant(sb, $"    bool has_{f.Name};");
                }
                AppendInvariant(sb, $"    {cType} {f.Name};");
            }
            AppendInvariant(sb, $"}} {p.Name};");
            _ = sb.AppendLine();
            _ = sb.AppendLine("#if defined(_MSC_VER) || defined(__GNUC__) || defined(__clang__)");
            _ = sb.AppendLine("    #pragma pack(pop)");
            _ = sb.AppendLine("#endif");
            _ = sb.AppendLine();

            string lower = p.Name.ToLowerInvariant();
            AppendInvariant(sb, $"void {lower}_init({p.Name}* pkt);");
            AppendInvariant(sb, $"size_t {lower}_serialize(const {p.Name}* pkt, uint8_t* buf, size_t buf_size);");
            AppendInvariant(sb, $"size_t {lower}_deserialize({p.Name}* pkt, const uint8_t* buf, size_t buf_size);");
            AppendInvariant(sb, $"bool {lower}_equals(const {p.Name}* a, const {p.Name}* b);");
            if (p.Fields.Any(f => f.CType == ProtocolConstants.StringCType || f.CType.EndsWith("Array", StringComparison.Ordinal)))
            {
                AppendInvariant(sb, $"void {lower}_free({p.Name}* pkt);");
            }
            _ = sb.AppendLine();
        }

        _ = sb.AppendLine("#ifdef __cplusplus");
        _ = sb.AppendLine("}");
        _ = sb.AppendLine("#endif");

        return sb.ToString();
    }

    private static string GenerateSource(IReadOnlyList<PacketSchema> nonHeaderPackets)
    {
        StringBuilder sb = new(65536);

        _ = sb.AppendLine("// <auto-generated/>");
        _ = sb.AppendLine("#include \"packets.h\"");
        _ = sb.AppendLine("#include <stdlib.h>");
        _ = sb.AppendLine();

        _ = sb.AppendLine("void nalix_string_free(NalixString* s) {");
        _ = sb.AppendLine("    if (s && s->data) { free(s->data); s->data = NULL; s->length = 0; }");
        _ = sb.AppendLine("}");
        _ = sb.AppendLine();
        _ = sb.AppendLine("void byte_array_free(ByteArray* arr) { if (arr && arr->data) { free(arr->data); arr->data = NULL; arr->count = 0; } }");
        _ = sb.AppendLine("void int8_array_free(Int8Array* arr) { if (arr && arr->data) { free(arr->data); arr->data = NULL; arr->count = 0; } }");
        _ = sb.AppendLine("void int16_array_free(Int16Array* arr) { if (arr && arr->data) { free(arr->data); arr->data = NULL; arr->count = 0; } }");
        _ = sb.AppendLine("void uint16_array_free(UInt16Array* arr) { if (arr && arr->data) { free(arr->data); arr->data = NULL; arr->count = 0; } }");
        _ = sb.AppendLine("void int32_array_free(Int32Array* arr) { if (arr && arr->data) { free(arr->data); arr->data = NULL; arr->count = 0; } }");
        _ = sb.AppendLine("void uint32_array_free(UInt32Array* arr) { if (arr && arr->data) { free(arr->data); arr->data = NULL; arr->count = 0; } }");
        _ = sb.AppendLine("void int64_array_free(Int64Array* arr) { if (arr && arr->data) { free(arr->data); arr->data = NULL; arr->count = 0; } }");
        _ = sb.AppendLine("void uint64_array_free(UInt64Array* arr) { if (arr && arr->data) { free(arr->data); arr->data = NULL; arr->count = 0; } }");
        _ = sb.AppendLine("void float_array_free(FloatArray* arr) { if (arr && arr->data) { free(arr->data); arr->data = NULL; arr->count = 0; } }");
        _ = sb.AppendLine("void double_array_free(DoubleArray* arr) { if (arr && arr->data) { free(arr->data); arr->data = NULL; arr->count = 0; } }");
        _ = sb.AppendLine();
        _ = sb.AppendLine("void string_array_free(StringArray* arr) {");
        _ = sb.AppendLine("    if (arr && arr->data) {");
        _ = sb.AppendLine("        for (int32_t i = 0; i < arr->count; i++) {");
        _ = sb.AppendLine("            nalix_string_free(&arr->data[i]);");
        _ = sb.AppendLine("        }");
        _ = sb.AppendLine("        free(arr->data);");
        _ = sb.AppendLine("        arr->data = NULL;");
        _ = sb.AppendLine("        arr->count = 0;");
        _ = sb.AppendLine("    }");
        _ = sb.AppendLine("}");
        _ = sb.AppendLine();

        _ = sb.AppendLine("size_t packet_header_serialize(const PacketHeader* header, uint8_t* buf, size_t buf_size)");
        _ = sb.AppendLine("{");
        _ = sb.AppendLine("    if (!header || !buf || buf_size < PACKET_HEADER_SIZE) return 0;");
        _ = sb.AppendLine("    buf[0] = (uint8_t)(header->OpCode & 0xFF);");
        _ = sb.AppendLine("    buf[1] = (uint8_t)((header->OpCode >> 8) & 0xFF);");
        _ = sb.AppendLine("    buf[2] = header->Flags;");
        _ = sb.AppendLine("    buf[3] = header->Priority;");
        _ = sb.AppendLine("    buf[4] = (uint8_t)(header->SequenceId & 0xFF);");
        _ = sb.AppendLine("    buf[5] = (uint8_t)((header->SequenceId >> 8) & 0xFF);");
        _ = sb.AppendLine("    return PACKET_HEADER_SIZE;");
        _ = sb.AppendLine("}");
        _ = sb.AppendLine();

        _ = sb.AppendLine("size_t packet_header_deserialize(PacketHeader* header, const uint8_t* buf, size_t buf_size)");
        _ = sb.AppendLine("{");
        _ = sb.AppendLine("    if (!header || !buf || buf_size < PACKET_HEADER_SIZE) return 0;");
        _ = sb.AppendLine("    header->OpCode = (uint16_t)(buf[0] | ((uint16_t)buf[1] << 8));");
        _ = sb.AppendLine("    header->Flags = buf[2];");
        _ = sb.AppendLine("    header->Priority = buf[3];");
        _ = sb.AppendLine("    header->SequenceId = (uint16_t)(buf[4] | ((uint16_t)buf[5] << 8));");
        _ = sb.AppendLine("    return PACKET_HEADER_SIZE;");
        _ = sb.AppendLine("}");
        _ = sb.AppendLine();

        foreach (PacketSchema p in nonHeaderPackets)
        {
            string name = p.Name;
            string lower = name.ToLowerInvariant();
            int fixedSize = CalculateFixedSize(p);

            FieldSchema? headerField = p.Fields.FirstOrDefault(f => f.IsHeader || f.CType == ProtocolConstants.PacketHeaderName);
            string headerName = headerField?.Name ?? "Header";

            // Init helper
            AppendInvariant(sb, $"void {lower}_init({name}* pkt)");
            _ = sb.AppendLine("{");
            _ = sb.AppendLine("    if (!pkt) return;");
            AppendInvariant(sb, $"    memset(pkt, 0, sizeof({name}));");
            AppendInvariant(sb, $"    pkt->{headerName}.OpCode = PACKET_{p.Name.ToUpperInvariant()}_OPCODE;");
            _ = sb.AppendLine("}");
            _ = sb.AppendLine();

            if (p.HasVariableFields)
            {
                // Variable-size serialize
                AppendInvariant(sb, $"size_t {lower}_serialize(const {name}* pkt, uint8_t* buf, size_t buf_size)");
                _ = sb.AppendLine("{");
                AppendInvariant(sb, $"    if (!pkt || !buf || buf_size < {fixedSize}) return 0;");
                _ = sb.AppendLine("    uint8_t* ptr = buf;");
                _ = sb.AppendLine();
                foreach (FieldSchema field in p.Fields)
                {
                    WriteSerializeField(sb, field);
                }
                _ = sb.AppendLine("    return (size_t)(ptr - buf);");
                _ = sb.AppendLine("}");
                _ = sb.AppendLine();

                // Variable-size deserialize
                AppendInvariant(sb, $"size_t {lower}_deserialize({name}* pkt, const uint8_t* buf, size_t buf_size)");
                _ = sb.AppendLine("{");
                AppendInvariant(sb, $"    if (!pkt || !buf || buf_size < {fixedSize}) return 0;");
                _ = sb.AppendLine("    const uint8_t* ptr = buf;");
                _ = sb.AppendLine();
                foreach (FieldSchema field in p.Fields)
                {
                    WriteDeserializeField(sb, field);
                }
                _ = sb.AppendLine("    return (size_t)(ptr - buf);");
                _ = sb.AppendLine("}");
                _ = sb.AppendLine();

                // Field-by-field equals for variable packets
                AppendInvariant(sb, $"bool {lower}_equals(const {name}* a, const {name}* b)");
                _ = sb.AppendLine("{");
                _ = sb.AppendLine("    if (!a || !b) return false;");
                foreach (FieldSchema field in p.Fields)
                {
                    WriteEqualsField(sb, field);
                }
                _ = sb.AppendLine("    return true;");
                _ = sb.AppendLine("}");
                _ = sb.AppendLine();

                // Free helper for dynamic fields
                if (p.Fields.Any(f => f.CType == ProtocolConstants.StringCType || f.CType.EndsWith("Array", StringComparison.Ordinal)))
                {
                    AppendInvariant(sb, $"void {lower}_free({name}* pkt)");
                    _ = sb.AppendLine("{");
                    _ = sb.AppendLine("    if (!pkt) return;");
                    foreach (FieldSchema field in p.Fields)
                    {
                        if (field.CType == ProtocolConstants.StringCType)
                        {
                            AppendInvariant(sb, $"    nalix_string_free(&pkt->{field.Name});");
                        }
                        else if (field.CType == "StringArray")
                        {
                            AppendInvariant(sb, $"    string_array_free(&pkt->{field.Name});");
                        }
                        else if (field.CType.EndsWith("Array", StringComparison.Ordinal))
                        {
                            string helper = GetArrayFreeHelper(field.CType);
                            AppendInvariant(sb, $"    {helper}(&pkt->{field.Name});");
                        }
                    }
                    _ = sb.AppendLine("}");
                    _ = sb.AppendLine();
                }
            }
            else
            {
                // Fixed-size serialize
                AppendInvariant(sb, $"size_t {lower}_serialize(const {name}* pkt, uint8_t* buf, size_t buf_size)");
                _ = sb.AppendLine("{");
                AppendInvariant(sb, $"    if (!pkt || !buf || buf_size < {fixedSize}) return 0;");
                _ = sb.AppendLine("    uint8_t* ptr = buf;");
                _ = sb.AppendLine();
                foreach (FieldSchema field in p.Fields)
                {
                    WriteSerializeField(sb, field);
                }
                AppendInvariant(sb, $"    return {fixedSize};");
                _ = sb.AppendLine("}");
                _ = sb.AppendLine();

                // Fixed-size deserialize
                AppendInvariant(sb, $"size_t {lower}_deserialize({name}* pkt, const uint8_t* buf, size_t buf_size)");
                _ = sb.AppendLine("{");
                AppendInvariant(sb, $"    if (!pkt || !buf || buf_size < {fixedSize}) return 0;");
                _ = sb.AppendLine("    const uint8_t* ptr = buf;");
                _ = sb.AppendLine();
                foreach (FieldSchema field in p.Fields)
                {
                    WriteDeserializeField(sb, field);
                }
                AppendInvariant(sb, $"    return {fixedSize};");
                _ = sb.AppendLine("}");
                _ = sb.AppendLine();

                // memcmp equals for fixed-size
                AppendInvariant(sb, $"bool {lower}_equals(const {name}* a, const {name}* b)");
                _ = sb.AppendLine("{");
                _ = sb.AppendLine("    if (!a || !b) return false;");
                AppendInvariant(sb, $"    return memcmp(a, b, sizeof({name})) == 0;");
                _ = sb.AppendLine("}");
                _ = sb.AppendLine();
            }
        }

        return sb.ToString();
    }

    private static void WriteSerializeField(StringBuilder sb, FieldSchema field)
    {
        string cs = field.CSharpType;
        string name = field.Name;
        int size = field.Size;

        if (field.IsNullable)
        {
            AppendInvariant(sb, $"    if (pkt->has_{name}) {{");
            _ = sb.AppendLine("        ptr[0] = 1; ptr += 1;");
            if (field.CType != ProtocolConstants.StringCType && !field.CType.EndsWith("Array", StringComparison.Ordinal))
            {
                AppendInvariant(sb, $"        if ((size_t)(ptr - buf) + {size} > buf_size) return 0;");
            }
        }

        string indent = field.IsNullable ? "    " : "";

        if (cs.Contains(ProtocolConstants.PacketHeaderName, StringComparison.Ordinal))
        {
            AppendInvariant(sb, $"    {indent}memcpy(ptr, &pkt->{name}, PACKET_HEADER_SIZE); ptr += PACKET_HEADER_SIZE;");
        }
        else if (cs == ProtocolConstants.Bytes32FullName || field.CType is "Bytes32" or "Bytes16" or "Bytes64" or "Guid" or "Decimal" or "DateTimeOffset" or "int128_t" or "uint128_t" || size > 8)
        {
            AppendInvariant(sb, $"    {indent}memcpy(ptr, &pkt->{name}, {size}); ptr += {size};");
        }
        else if (field.CType == ProtocolConstants.StringCType)
        {
            AppendInvariant(sb, $"    {indent}{{");
            AppendInvariant(sb, $"    {indent}    int32_t slen = pkt->{name}.length;");
            AppendInvariant(sb, $"    {indent}    if ((size_t)(ptr - buf) + 4 + (slen > 0 ? (size_t)slen : 0) > buf_size) return 0;");
            AppendInvariant(sb, $"    {indent}    memcpy(ptr, &slen, 4); ptr += 4;");
            AppendInvariant(sb, $"    {indent}    if (slen > 0 && pkt->{name}.data) {{ memcpy(ptr, pkt->{name}.data, (size_t)slen); ptr += (size_t)slen; }}");
            AppendInvariant(sb, $"    {indent}}}");
        }
        else if (field.CType == "StringArray")
        {
            AppendInvariant(sb, $"    {indent}{{");
            AppendInvariant(sb, $"    {indent}    int32_t cnt = pkt->{name}.count;");
            AppendInvariant(sb, $"    {indent}    if ((size_t)(ptr - buf) + 4 > buf_size) return 0;");
            AppendInvariant(sb, $"    {indent}    memcpy(ptr, &cnt, 4); ptr += 4;");
            AppendInvariant(sb, $"    {indent}    if (cnt > 0 && pkt->{name}.data) {{");
            AppendInvariant(sb, $"    {indent}        for (int32_t i = 0; i < cnt; i++) {{");
            AppendInvariant(sb, $"    {indent}            int32_t slen = pkt->{name}.data[i].length;");
            AppendInvariant(sb, $"    {indent}            if ((size_t)(ptr - buf) + 4 + (slen > 0 ? (size_t)slen : 0) > buf_size) return 0;");
            AppendInvariant(sb, $"    {indent}            memcpy(ptr, &slen, 4); ptr += 4;");
            AppendInvariant(sb, $"    {indent}            if (slen > 0 && pkt->{name}.data[i].data) {{ memcpy(ptr, pkt->{name}.data[i].data, (size_t)slen); ptr += (size_t)slen; }}");
            AppendInvariant(sb, $"    {indent}        }}");
            AppendInvariant(sb, $"    {indent}    }}");
            AppendInvariant(sb, $"    {indent}}}");
        }
        else if (field.CType.EndsWith("Array", StringComparison.Ordinal))
        {
            string elemCType = GetArrayElementCType(field.CType);
            AppendInvariant(sb, $"    {indent}{{");
            AppendInvariant(sb, $"    {indent}    int32_t cnt = pkt->{name}.count;");
            AppendInvariant(sb, $"    {indent}    if ((size_t)(ptr - buf) + 4 + (cnt > 0 ? (size_t)cnt * sizeof({elemCType}) : 0) > buf_size) return 0;");
            AppendInvariant(sb, $"    {indent}    memcpy(ptr, &cnt, 4); ptr += 4;");
            AppendInvariant(sb, $"    {indent}    if (cnt > 0 && pkt->{name}.data) {{ memcpy(ptr, pkt->{name}.data, (size_t)cnt * sizeof({elemCType})); ptr += (size_t)cnt * sizeof({elemCType}); }}");
            AppendInvariant(sb, $"    {indent}}}");
        }
        else if (size == 1)
        {
            AppendInvariant(sb, $"    {indent}ptr[0] = (uint8_t)pkt->{name}; ptr += 1;");
        }
        else if (size == 2)
        {
            AppendInvariant(sb, $"    {indent}ptr[0] = (uint8_t)(pkt->{name});");
            AppendInvariant(sb, $"    {indent}ptr[1] = (uint8_t)((pkt->{name}) >> 8); ptr += 2;");
        }
        else if (size == 4)
        {
            AppendInvariant(sb, $"    {indent}ptr[0] = (uint8_t)(pkt->{name});");
            AppendInvariant(sb, $"    {indent}ptr[1] = (uint8_t)((pkt->{name}) >> 8);");
            AppendInvariant(sb, $"    {indent}ptr[2] = (uint8_t)((pkt->{name}) >> 16);");
            AppendInvariant(sb, $"    {indent}ptr[3] = (uint8_t)((pkt->{name}) >> 24); ptr += 4;");
        }
        else if (size == 8)
        {
            AppendInvariant(sb, $"    {indent}ptr[0] = (uint8_t)(pkt->{name});");
            AppendInvariant(sb, $"    {indent}ptr[1] = (uint8_t)((pkt->{name}) >> 8);");
            AppendInvariant(sb, $"    {indent}ptr[2] = (uint8_t)((pkt->{name}) >> 16);");
            AppendInvariant(sb, $"    {indent}ptr[3] = (uint8_t)((pkt->{name}) >> 24);");
            AppendInvariant(sb, $"    {indent}ptr[4] = (uint8_t)((pkt->{name}) >> 32);");
            AppendInvariant(sb, $"    {indent}ptr[5] = (uint8_t)((pkt->{name}) >> 40);");
            AppendInvariant(sb, $"    {indent}ptr[6] = (uint8_t)((pkt->{name}) >> 48);");
            AppendInvariant(sb, $"    {indent}ptr[7] = (uint8_t)((pkt->{name}) >> 56); ptr += 8;");
        }

        if (field.IsNullable)
        {
            _ = sb.AppendLine("    } else {");
            _ = sb.AppendLine("        ptr[0] = 0; ptr += 1;");
            _ = sb.AppendLine("    }");
        }
    }

    private static void WriteDeserializeField(StringBuilder sb, FieldSchema field)
    {
        string cs = field.CSharpType;
        string name = field.Name;
        int size = field.Size;

        if (field.IsNullable)
        {
            _ = sb.AppendLine("    if (ptr[0] == 1) {");
            AppendInvariant(sb, $"        pkt->has_{name} = true;");
            _ = sb.AppendLine("        ptr += 1;");
            if (field.CType != ProtocolConstants.StringCType && !field.CType.EndsWith("Array", StringComparison.Ordinal))
            {
                AppendInvariant(sb, $"        if ((size_t)(ptr - buf) + {size} > buf_size) return 0;");
            }
        }

        string indent = field.IsNullable ? "    " : "";

        if (cs.Contains(ProtocolConstants.PacketHeaderName, StringComparison.Ordinal))
        {
            AppendInvariant(sb, $"    {indent}memcpy(&pkt->{name}, ptr, PACKET_HEADER_SIZE); ptr += PACKET_HEADER_SIZE;");
        }
        else if (cs == ProtocolConstants.Bytes32FullName || field.CType is "Bytes32" or "Bytes16" or "Bytes64" or "Guid" or "Decimal" or "DateTimeOffset" or "int128_t" or "uint128_t" || size > 8)
        {
            AppendInvariant(sb, $"    {indent}memcpy(&pkt->{name}, ptr, {size}); ptr += {size};");
        }
        else if (field.CType == ProtocolConstants.StringCType)
        {
            AppendInvariant(sb, $"    {indent}{{");
            AppendInvariant(sb, $"    {indent}    int32_t slen;");
            AppendInvariant(sb, $"    {indent}    memcpy(&slen, ptr, 4); ptr += 4;");
            AppendInvariant(sb, $"    {indent}    pkt->{name}.length = slen;");
            AppendInvariant(sb, $"    {indent}    if (slen > 0) {{");
            AppendInvariant(sb, $"    {indent}        if ((size_t)(ptr - buf) + (size_t)slen > buf_size) return 0;");
            AppendInvariant(sb, $"    {indent}        pkt->{name}.data = (uint8_t*)malloc((size_t)slen);");
            AppendInvariant(sb, $"    {indent}        memcpy(pkt->{name}.data, ptr, (size_t)slen);");
            AppendInvariant(sb, $"    {indent}        ptr += (size_t)slen;");
            AppendInvariant(sb, $"    {indent}    }} else {{");
            AppendInvariant(sb, $"    {indent}        pkt->{name}.data = NULL;");
            AppendInvariant(sb, $"    {indent}    }}");
            AppendInvariant(sb, $"    {indent}}}");
        }
        else if (field.CType == "StringArray")
        {
            AppendInvariant(sb, $"    {indent}{{");
            AppendInvariant(sb, $"    {indent}    if ((size_t)(ptr - buf) + 4 > buf_size) return 0;");
            AppendInvariant(sb, $"    {indent}    int32_t cnt = 0;");
            AppendInvariant(sb, $"    {indent}    memcpy(&cnt, ptr, 4); ptr += 4;");
            AppendInvariant(sb, $"    {indent}    pkt->{name}.count = cnt;");
            AppendInvariant(sb, $"    {indent}    if (cnt > 0) {{");
            AppendInvariant(sb, $"    {indent}        pkt->{name}.data = (NalixString*)malloc((size_t)cnt * sizeof(NalixString));");
            AppendInvariant(sb, $"    {indent}        if (!pkt->{name}.data) return 0;");
            AppendInvariant(sb, $"    {indent}        for (int32_t i = 0; i < cnt; i++) {{");
            AppendInvariant(sb, $"    {indent}            if ((size_t)(ptr - buf) + 4 > buf_size) return 0;");
            AppendInvariant(sb, $"    {indent}            int32_t slen = 0;");
            AppendInvariant(sb, $"    {indent}            memcpy(&slen, ptr, 4); ptr += 4;");
            AppendInvariant(sb, $"    {indent}            pkt->{name}.data[i].length = slen;");
            AppendInvariant(sb, $"    {indent}            if (slen > 0) {{");
            AppendInvariant(sb, $"    {indent}                if ((size_t)(ptr - buf) + (size_t)slen > buf_size) return 0;");
            AppendInvariant(sb, $"    {indent}                pkt->{name}.data[i].data = (uint8_t*)malloc((size_t)slen);");
            AppendInvariant(sb, $"    {indent}                if (!pkt->{name}.data[i].data) return 0;");
            AppendInvariant(sb, $"    {indent}                memcpy(pkt->{name}.data[i].data, ptr, (size_t)slen); ptr += (size_t)slen;");
            AppendInvariant(sb, $"    {indent}            }} else {{");
            AppendInvariant(sb, $"    {indent}                pkt->{name}.data[i].data = NULL;");
            AppendInvariant(sb, $"    {indent}            }}");
            AppendInvariant(sb, $"    {indent}        }}");
            AppendInvariant(sb, $"    {indent}    }} else {{");
            AppendInvariant(sb, $"    {indent}        pkt->{name}.data = NULL;");
            AppendInvariant(sb, $"    {indent}    }}");
            AppendInvariant(sb, $"    {indent}}}");
        }
        else if (field.CType.EndsWith("Array", StringComparison.Ordinal))
        {
            string elemCType = GetArrayElementCType(field.CType);
            AppendInvariant(sb, $"    {indent}{{");
            AppendInvariant(sb, $"    {indent}    if ((size_t)(ptr - buf) + 4 > buf_size) return 0;");
            AppendInvariant(sb, $"    {indent}    int32_t cnt = 0;");
            AppendInvariant(sb, $"    {indent}    memcpy(&cnt, ptr, 4); ptr += 4;");
            AppendInvariant(sb, $"    {indent}    pkt->{name}.count = cnt;");
            AppendInvariant(sb, $"    {indent}    if (cnt > 0) {{");
            AppendInvariant(sb, $"    {indent}        size_t total_bytes = (size_t)cnt * sizeof({elemCType});");
            AppendInvariant(sb, $"    {indent}        if ((size_t)(ptr - buf) + total_bytes > buf_size) return 0;");
            AppendInvariant(sb, $"    {indent}        pkt->{name}.data = ({elemCType}*)malloc(total_bytes);");
            AppendInvariant(sb, $"    {indent}        if (!pkt->{name}.data) return 0;");
            AppendInvariant(sb, $"    {indent}        memcpy(pkt->{name}.data, ptr, total_bytes); ptr += total_bytes;");
            AppendInvariant(sb, $"    {indent}    }} else {{");
            AppendInvariant(sb, $"    {indent}        pkt->{name}.data = NULL;");
            AppendInvariant(sb, $"    {indent}    }}");
            AppendInvariant(sb, $"    {indent}}}");
        }
        else if (size == 1)
        {
            AppendInvariant(sb, $"    {indent}pkt->{name} = ({field.CType})ptr[0]; ptr += 1;");
        }
        else if (size == 2)
        {
            AppendInvariant(sb, $"    {indent}pkt->{name} = ({field.CType})((uint16_t)ptr[0] | ((uint16_t)ptr[1] << 8)); ptr += 2;");
        }
        else if (size == 4)
        {
            AppendInvariant(sb, $"    {indent}pkt->{name} = ({field.CType})((uint32_t)ptr[0] | ((uint32_t)ptr[1] << 8) | ((uint32_t)ptr[2] << 16) | ((uint32_t)ptr[3] << 24)); ptr += 4;");
        }
        else if (size == 8)
        {
            AppendInvariant(sb, $"    {indent}pkt->{name} = ({field.CType})((uint64_t)ptr[0] | ((uint64_t)ptr[1] << 8) | ((uint64_t)ptr[2] << 16) | ((uint64_t)ptr[3] << 24) | ((uint64_t)ptr[4] << 32) | ((uint64_t)ptr[5] << 40) | ((uint64_t)ptr[6] << 48) | ((uint64_t)ptr[7] << 56)); ptr += 8;");
        }

        if (field.IsNullable)
        {
            _ = sb.AppendLine("    } else {");
            AppendInvariant(sb, $"        pkt->has_{name} = false;");
            _ = sb.AppendLine("        ptr += 1;");
            _ = sb.AppendLine("    }");
        }
    }

    private static void WriteEqualsField(StringBuilder sb, FieldSchema field)
    {
        string name = field.Name;

        if (field.IsNullable)
        {
            AppendInvariant(sb, $"    if (a->has_{name} != b->has_{name}) return false;");
            AppendInvariant(sb, $"    if (a->has_{name}) {{");
        }

        string indent = field.IsNullable ? "    " : "";

        if (field.CType == ProtocolConstants.StringCType)
        {
            AppendInvariant(sb, $"    {indent}if (a->{name}.length != b->{name}.length) return false;");
            AppendInvariant(sb, $"    {indent}if (a->{name}.length > 0 && memcmp(a->{name}.data, b->{name}.data, (size_t)a->{name}.length) != 0) return false;");
        }
        else if (field.CType == "StringArray")
        {
            AppendInvariant(sb, $"    {indent}if (a->{name}.count != b->{name}.count) return false;");
            AppendInvariant(sb, $"    {indent}for (int32_t i = 0; i < a->{name}.count; i++) {{");
            AppendInvariant(sb, $"    {indent}    if (a->{name}.data[i].length != b->{name}.data[i].length) return false;");
            AppendInvariant(sb, $"    {indent}    if (a->{name}.data[i].length > 0 && memcmp(a->{name}.data[i].data, b->{name}.data[i].data, (size_t)a->{name}.data[i].length) != 0) return false;");
            AppendInvariant(sb, $"    {indent}}}");
        }
        else if (field.CType.EndsWith("Array", StringComparison.Ordinal))
        {
            string elemCType = GetArrayElementCType(field.CType);
            AppendInvariant(sb, $"    {indent}if (a->{name}.count != b->{name}.count) return false;");
            AppendInvariant(sb, $"    {indent}if (a->{name}.count > 0 && memcmp(a->{name}.data, b->{name}.data, (size_t)a->{name}.count * sizeof({elemCType})) != 0) return false;");
        }
        else if (field.CSharpType.Contains(ProtocolConstants.PacketHeaderName, StringComparison.Ordinal))
        {
            AppendInvariant(sb, $"    {indent}if (memcmp(&a->{name}, &b->{name}, PACKET_HEADER_SIZE) != 0) return false;");
        }
        else
        {
            AppendInvariant(sb, $"    {indent}if (memcmp(&a->{name}, &b->{name}, {field.Size}) != 0) return false;");
        }

        if (field.IsNullable)
        {
            _ = sb.AppendLine("    }");
        }
    }

    private static int CalculateFixedSize(PacketSchema packet)
    {
        int size = 0;
        foreach (FieldSchema f in packet.Fields)
        {
            if (f.IsNullable)
            {
                size += 1;
            }
            else if (f.CType == ProtocolConstants.StringCType || f.CType.EndsWith("Array", StringComparison.Ordinal))
            {
                size += 4;
            }
            else
            {
                size += f.Size;
            }
        }
        return size;
    }

