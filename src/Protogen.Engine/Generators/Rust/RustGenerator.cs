using System.Text;
using Protogen.Core.Constants;
using Protogen.Core.Contracts;
using Protogen.Core.Models;

namespace Protogen.Engine.Generators.Rust;

/// <summary>
/// Code generator for native Rust structs and serialize/deserialize implementations.
/// Compatible with Nalix v14 6-byte header.
/// Pure safe Rust code without FFI.
/// </summary>
public sealed class RustGenerator : ICodeGenerator
{
    public string LanguageName => "Rust";

    public IReadOnlyList<GeneratedFile> Generate(IReadOnlyList<PacketSchema> packets)
    {
        PacketSchema? headerSchema = packets.FirstOrDefault(p => p.Name == ProtocolConstants.PacketHeaderName);
        List<PacketSchema> nonHeaderPackets = [.. packets.Where(p => p.Name != ProtocolConstants.PacketHeaderName)];

        string main = GenerateMain(headerSchema, nonHeaderPackets);
        string tests = GenerateTests(nonHeaderPackets);

        return
        [
            new GeneratedFile("packets.rs", main, "src/"),
            new GeneratedFile("packets_tests.rs", tests, "src/")
        ];
    }

    private static string GenerateMain(PacketSchema? headerSchema, IReadOnlyList<PacketSchema> nonHeaderPackets)
    {
        StringBuilder sb = new(65536);

        _ = sb.AppendLine("// <auto-generated/>");
        _ = sb.AppendLine("// Generated by Protogen — RustGenerator");
        _ = sb.AppendLine("// DO NOT EDIT MANUALLY");
        _ = sb.AppendLine();
        _ = sb.AppendLine("#![allow(dead_code)]");
        _ = sb.AppendLine("#![allow(unused_variables)]");
        _ = sb.AppendLine("#![allow(unused_assignments)]");
        _ = sb.AppendLine();

        if (headerSchema != null)
        {
            GenerateHeaderStruct(sb, headerSchema);
        }

        GeneratePacketStructs(sb, nonHeaderPackets);

        _ = sb.AppendLine();
        _ = sb.AppendLine("#[cfg(test)]");
        _ = sb.AppendLine("#[path = \"packets_tests.rs\"]");
        _ = sb.AppendLine("mod tests;");

        return sb.ToString();
    }

    private static void GenerateHeaderStruct(StringBuilder sb, PacketSchema header)
    {
        AppendInvariant(sb, $"/// Common Nalix v14 {ProtocolConstants.PacketHeaderSize}-byte packet header.");
        _ = sb.AppendLine("#[repr(C)]");
        _ = sb.AppendLine("#[derive(Debug, Clone, Copy, Default, PartialEq, Eq)]");
        _ = sb.AppendLine("pub struct PacketHeader {");

        foreach (FieldSchema f in header.Fields)
        {
            AppendInvariant(sb, $"    pub {ToSnakeCase(f.Name)}: {f.RustType},");
        }

        _ = sb.AppendLine("}");
        _ = sb.AppendLine();
        _ = sb.AppendLine("impl PacketHeader {");
        AppendInvariant(sb, $"    pub const SIZE: usize = {ProtocolConstants.PacketHeaderSize};");
        _ = sb.AppendLine();
        _ = sb.AppendLine("    pub fn serialize_to_bytes(&self) -> [u8; 6] {");
        _ = sb.AppendLine("        let mut buf = [0u8; 6];");
        _ = sb.AppendLine("        buf[0..2].copy_from_slice(&self.op_code.to_le_bytes());");
        _ = sb.AppendLine("        buf[2] = self.flags;");
        _ = sb.AppendLine("        buf[3] = self.priority;");
        _ = sb.AppendLine("        buf[4..6].copy_from_slice(&self.sequence_id.to_le_bytes());");
        _ = sb.AppendLine("        buf");
        _ = sb.AppendLine("    }");
        _ = sb.AppendLine();
        _ = sb.AppendLine("    pub fn serialize(&self, buf: &mut [u8]) -> Result<usize, ()> {");
        _ = sb.AppendLine("        if buf.len() < Self::SIZE { return Err(()); }");
        _ = sb.AppendLine("        buf[..Self::SIZE].copy_from_slice(&self.serialize_to_bytes());");
        _ = sb.AppendLine("        Ok(Self::SIZE)");
        _ = sb.AppendLine("    }");
        _ = sb.AppendLine();
        _ = sb.AppendLine("    pub fn deserialize(buf: &[u8]) -> Result<Self, ()> {");
        _ = sb.AppendLine("        if buf.len() < Self::SIZE { return Err(()); }");
        _ = sb.AppendLine("        let op_code = u16::from_le_bytes([buf[0], buf[1]]);");
        _ = sb.AppendLine("        let flags = buf[2];");
        _ = sb.AppendLine("        let priority = buf[3];");
        _ = sb.AppendLine("        let sequence_id = u16::from_le_bytes([buf[4], buf[5]]);");
        _ = sb.AppendLine("        Ok(Self { op_code, flags, priority, sequence_id })");
        _ = sb.AppendLine("    }");
        _ = sb.AppendLine("}");
        _ = sb.AppendLine();
    }

    private static void GeneratePacketStructs(StringBuilder sb, IReadOnlyList<PacketSchema> packets)
    {
        foreach (PacketSchema packet in packets)
        {
            string name = packet.Name;
            int fixedSize = CalculateFixedSize(packet);
            int wireSize = packet.CalculateWireSize();

            if (packet.HasVariableFields)
            {
                AppendInvariant(sb, $"/// {name} — fixed: {fixedSize} bytes + variable, opcode: 0x{packet.OpCode:X4}");
            }
            else
            {
                AppendInvariant(sb, $"/// {name} — wire size: {wireSize} bytes, opcode: 0x{packet.OpCode:X4}");
            }

            if (packet.HasVariableFields)
            {
                _ = sb.AppendLine("#[derive(Debug, Default, PartialEq)]");
            }
            else
            {
                _ = sb.AppendLine("#[repr(C)]");
                _ = sb.AppendLine("#[derive(Debug, Clone, Copy, Default, PartialEq)]");
            }

            AppendInvariant(sb, $"pub struct {name} {{");

            foreach (FieldSchema f in packet.Fields)
            {
                string rustType = f.RustType;
                if (f.IsNullable)
                {
                    rustType = $"Option<{rustType}>";
                }
                AppendInvariant(sb, $"    pub {ToSnakeCase(f.Name)}: {rustType},");
            }

            _ = sb.AppendLine("}");
            _ = sb.AppendLine();
            AppendInvariant(sb, $"impl {name} {{");
            AppendInvariant(sb, $"    pub const FIXED_SIZE: usize = {fixedSize};");
            AppendInvariant(sb, $"    pub const OPCODE: u16 = 0x{packet.OpCode:X4};");
            _ = sb.AppendLine();

            if (packet.HasVariableFields)
            {
                _ = sb.AppendLine("    pub fn serialize(&self, buf: &mut [u8]) -> Result<usize, ()> {");
                AppendInvariant(sb, $"        if buf.len() < Self::FIXED_SIZE {{ return Err(()); }}");
                _ = sb.AppendLine("        let mut offset = 0;");

                foreach (FieldSchema f in packet.Fields)
                {
                    WriteRustSerializeField(sb, f, "self", "        ");
                }

                _ = sb.AppendLine("        Ok(offset)");
                _ = sb.AppendLine("    }");
                _ = sb.AppendLine();

                _ = sb.AppendLine("    pub fn deserialize(buf: &[u8]) -> Result<Self, ()> {");
                AppendInvariant(sb, $"        if buf.len() < Self::FIXED_SIZE {{ return Err(()); }}");
                _ = sb.AppendLine("        let mut pkt = Self::default();");
                _ = sb.AppendLine("        let mut offset = 0;");

                foreach (FieldSchema f in packet.Fields)
                {
                    WriteRustDeserializeField(sb, f, "pkt", "        ");
                }

                _ = sb.AppendLine("        Ok(pkt)");
                _ = sb.AppendLine("    }");
            }
            else
            {
                _ = sb.AppendLine("    pub fn serialize(&self, buf: &mut [u8]) -> Result<usize, ()> {");
                AppendInvariant(sb, $"        if buf.len() < Self::FIXED_SIZE {{ return Err(()); }}");
                _ = sb.AppendLine("        let mut offset = 0;");

                foreach (FieldSchema f in packet.Fields)
                {
                    WriteRustSerializeField(sb, f, "self", "        ");
                }

                AppendInvariant(sb, $"        Ok(Self::FIXED_SIZE)");
                _ = sb.AppendLine("    }");
                _ = sb.AppendLine();

                _ = sb.AppendLine("    pub fn deserialize(buf: &[u8]) -> Result<Self, ()> {");
                AppendInvariant(sb, $"        if buf.len() < Self::FIXED_SIZE {{ return Err(()); }}");
                _ = sb.AppendLine("        let mut pkt = Self::default();");
                _ = sb.AppendLine("        let mut offset = 0;");

                foreach (FieldSchema f in packet.Fields)
                {
                    WriteRustDeserializeField(sb, f, "pkt", "        ");
                }

                _ = sb.AppendLine("        Ok(pkt)");
                _ = sb.AppendLine("    }");
            }

            _ = sb.AppendLine("}");
            _ = sb.AppendLine();
        }
    }

    private static int CalculateFixedSize(PacketSchema packet)
    {
        int size = 0;
        foreach (FieldSchema f in packet.Fields)
        {
            if (f.IsNullable)
            {
                size += 1;
            }
            else if (f.CType == ProtocolConstants.StringCType || f.CType.EndsWith("Array", StringComparison.Ordinal) || f.RustType.StartsWith("Vec<", StringComparison.Ordinal))
            {
                size += 4;
            }
            else
            {
                size += f.Size;
            }
        }
        return size;
    }

    private static void WriteRustSerializeField(StringBuilder sb, FieldSchema field, string obj, string indent)
    {
        string snake = ToSnakeCase(field.Name);
        string cs = field.CSharpType;
        int size = field.Size;

        if (field.IsNullable)
        {
            AppendInvariant(sb, $"{indent}match &{obj}.{snake} {{");
            AppendInvariant(sb, $"{indent}    Some(val) => {{");
            AppendInvariant(sb, $"{indent}        buf[offset] = 1;");
            AppendInvariant(sb, $"{indent}        offset += 1;");
            indent += "        ";
        }

        string valRef = field.IsNullable ? "val" : $"&{obj}.{snake}";
        string valDeref = field.IsNullable ? "(*val)" : $"{obj}.{snake}";

        if (cs.Contains(ProtocolConstants.PacketHeaderName, StringComparison.Ordinal))
        {
            AppendInvariant(sb, $"{indent}buf[offset..offset+{size}].copy_from_slice(&{valDeref}.serialize_to_bytes());");
            AppendInvariant(sb, $"{indent}offset += {size};");
        }
        else if (field.RustType is "u128" or "i128")
        {
            AppendInvariant(sb, $"{indent}buf[offset..offset+16].copy_from_slice(&{valDeref}.to_le_bytes());");
            AppendInvariant(sb, $"{indent}offset += 16;");
        }
        else if (cs == ProtocolConstants.Bytes32FullName || field.RustType.StartsWith("[u8; ", StringComparison.Ordinal) || size > 8)
        {
            AppendInvariant(sb, $"{indent}buf[offset..offset+{size}].copy_from_slice({valRef});");
            AppendInvariant(sb, $"{indent}offset += {size};");
        }
        else if (field.RustType == "Vec<Vec<u8>>")
        {
            AppendInvariant(sb, $"{indent}let cnt = {valDeref}.len() as i32;");
            AppendInvariant(sb, $"{indent}if offset + 4 > buf.len() {{ return Err(()); }}");
            AppendInvariant(sb, $"{indent}buf[offset..offset+4].copy_from_slice(&cnt.to_le_bytes());");
            AppendInvariant(sb, $"{indent}offset += 4;");
            AppendInvariant(sb, $"{indent}for s in &{valDeref} {{");
            AppendInvariant(sb, $"{indent}    let slen = s.len() as i32;");
            AppendInvariant(sb, $"{indent}    if offset + 4 + s.len() > buf.len() {{ return Err(()); }}");
            AppendInvariant(sb, $"{indent}    buf[offset..offset+4].copy_from_slice(&slen.to_le_bytes());");
            AppendInvariant(sb, $"{indent}    offset += 4;");
            AppendInvariant(sb, $"{indent}    buf[offset..offset+s.len()].copy_from_slice(s);");
            AppendInvariant(sb, $"{indent}    offset += s.len();");
            AppendInvariant(sb, $"{indent}}}");
        }
        else if (cs == "string" || cs == "System.String" || field.RustType == "Vec<u8>")
        {
            AppendInvariant(sb, $"{indent}let slen = {valDeref}.len() as i32;");
            AppendInvariant(sb, $"{indent}buf[offset..offset+4].copy_from_slice(&slen.to_le_bytes());");
            AppendInvariant(sb, $"{indent}offset += 4;");
            AppendInvariant(sb, $"{indent}if slen > 0 {{ buf[offset..offset+slen as usize].copy_from_slice({valRef}); offset += slen as usize; }}");
        }
        else if (field.RustType.StartsWith("Vec<", StringComparison.Ordinal))
        {
            string elemType = field.RustType.Substring(4, field.RustType.Length - 5);
            AppendInvariant(sb, $"{indent}let cnt = {valDeref}.len() as i32;");
            AppendInvariant(sb, $"{indent}let elem_size = std::mem::size_of::<{elemType}>();");
            AppendInvariant(sb, $"{indent}if offset + 4 + ({valDeref}.len() * elem_size) > buf.len() {{ return Err(()); }}");
            AppendInvariant(sb, $"{indent}buf[offset..offset+4].copy_from_slice(&cnt.to_le_bytes());");
            AppendInvariant(sb, $"{indent}offset += 4;");
            AppendInvariant(sb, $"{indent}for item in &{valDeref} {{");
            AppendInvariant(sb, $"{indent}    buf[offset..offset+elem_size].copy_from_slice(&item.to_le_bytes());");
            AppendInvariant(sb, $"{indent}    offset += elem_size;");
            AppendInvariant(sb, $"{indent}}}");
        }
        else if (size == 1)
        {
            AppendInvariant(sb, $"{indent}buf[offset] = {valDeref} as u8;");
            AppendInvariant(sb, $"{indent}offset += 1;");
        }
        else if (size == 2)
        {
            AppendInvariant(sb, $"{indent}buf[offset..offset+2].copy_from_slice(&({valDeref} as u16).to_le_bytes());");
            AppendInvariant(sb, $"{indent}offset += 2;");
        }
        else if (size == 4)
        {
            AppendInvariant(sb, $"{indent}buf[offset..offset+4].copy_from_slice(&({valDeref} as u32).to_le_bytes());");
            AppendInvariant(sb, $"{indent}offset += 4;");
        }
        else if (size == 8)
        {
            AppendInvariant(sb, $"{indent}buf[offset..offset+8].copy_from_slice(&({valDeref} as u64).to_le_bytes());");
            AppendInvariant(sb, $"{indent}offset += 8;");
        }

        if (field.IsNullable)
        {
            indent = indent.Substring(0, indent.Length - 8);
            AppendInvariant(sb, $"{indent}    }}");
            AppendInvariant(sb, $"{indent}    None => {{");
            AppendInvariant(sb, $"{indent}        buf[offset] = 0;");
            AppendInvariant(sb, $"{indent}        offset += 1;");
            AppendInvariant(sb, $"{indent}    }}");
            AppendInvariant(sb, $"{indent}}}");
        }
    }

    private static void WriteRustDeserializeField(StringBuilder sb, FieldSchema field, string obj, string indent)
    {
        string snake = ToSnakeCase(field.Name);
        string cs = field.CSharpType;
        int size = field.Size;

        if (field.IsNullable)
        {
            AppendInvariant(sb, $"{indent}if buf[offset] == 1 {{");
            AppendInvariant(sb, $"{indent}    offset += 1;");
            indent += "    ";
        }

        string target = field.IsNullable ? "let val" : $"{obj}.{snake}";

        if (cs.Contains(ProtocolConstants.PacketHeaderName, StringComparison.Ordinal))
        {
            AppendInvariant(sb, $"{indent}{target} = PacketHeader::deserialize(&buf[offset..offset+{size}]).map_err(|_| ())?;");
            AppendInvariant(sb, $"{indent}offset += {size};");
        }
        else if (field.RustType is "u128" or "i128")
        {
            AppendInvariant(sb, $"{indent}{target} = {field.RustType}::from_le_bytes(buf[offset..offset+16].try_into().unwrap());");
            AppendInvariant(sb, $"{indent}offset += 16;");
        }
        else if (cs == ProtocolConstants.Bytes32FullName || field.RustType.StartsWith("[u8; ", StringComparison.Ordinal) || size > 8)
        {
            if (field.IsNullable)
            {
                AppendInvariant(sb, $"{indent}let mut val = [0u8; {size}];");
                AppendInvariant(sb, $"{indent}val.copy_from_slice(&buf[offset..offset+{size}]);");
            }
            else
            {
                AppendInvariant(sb, $"{indent}{target}.copy_from_slice(&buf[offset..offset+{size}]);");
            }
            AppendInvariant(sb, $"{indent}offset += {size};");
        }
        else if (field.RustType == "Vec<Vec<u8>>")
        {
            AppendInvariant(sb, $"{indent}let cnt = i32::from_le_bytes(buf[offset..offset+4].try_into().unwrap());");
            AppendInvariant(sb, $"{indent}offset += 4;");
            if (field.IsNullable)
            {
                AppendInvariant(sb, $"{indent}let mut val = Vec::new();");
            }
            AppendInvariant(sb, $"{indent}if cnt > 0 {{");
            AppendInvariant(sb, $"{indent}    let elem_count = cnt as usize;");
            if (field.IsNullable)
            {
                AppendInvariant(sb, $"{indent}    val.reserve(elem_count);");
            }
            else
            {
                AppendInvariant(sb, $"{indent}    {obj}.{snake}.reserve(elem_count);");
            }
            AppendInvariant(sb, $"{indent}    for _ in 0..elem_count {{");
            AppendInvariant(sb, $"{indent}        if offset + 4 > buf.len() {{ return Err(()); }}");
            AppendInvariant(sb, $"{indent}        let slen = i32::from_le_bytes(buf[offset..offset+4].try_into().unwrap());");
            AppendInvariant(sb, $"{indent}        offset += 4;");
            AppendInvariant(sb, $"{indent}        if slen > 0 {{");
            AppendInvariant(sb, $"{indent}            let ulen = slen as usize;");
            AppendInvariant(sb, $"{indent}            if offset + ulen > buf.len() {{ return Err(()); }}");
            if (field.IsNullable)
            {
                AppendInvariant(sb, $"{indent}            val.push(buf[offset..offset+ulen].to_vec());");
            }
            else
            {
                AppendInvariant(sb, $"{indent}            {obj}.{snake}.push(buf[offset..offset+ulen].to_vec());");
            }
            AppendInvariant(sb, $"{indent}            offset += ulen;");
            AppendInvariant(sb, $"{indent}        }} else {{");
            if (field.IsNullable)
            {
                AppendInvariant(sb, $"{indent}            val.push(Vec::new());");
            }
            else
            {
                AppendInvariant(sb, $"{indent}            {obj}.{snake}.push(Vec::new());");
            }
            AppendInvariant(sb, $"{indent}        }}");
            AppendInvariant(sb, $"{indent}    }}");
            AppendInvariant(sb, $"{indent}}}");
        }
        else if (cs == "string" || cs == "System.String" || field.RustType == "Vec<u8>")
        {
            AppendInvariant(sb, $"{indent}let slen = i32::from_le_bytes(buf[offset..offset+4].try_into().unwrap());");
            AppendInvariant(sb, $"{indent}offset += 4;");
            if (field.IsNullable)
            {
                AppendInvariant(sb, $"{indent}let mut val = Vec::new();");
            }
            AppendInvariant(sb, $"{indent}if slen > 0 {{");
            AppendInvariant(sb, $"{indent}    if buf.len() < offset + slen as usize {{ return Err(()); }}");
            if (field.IsNullable)
            {
                AppendInvariant(sb, $"{indent}    val = buf[offset..offset+slen as usize].to_vec();");
            }
            else
            {
                AppendInvariant(sb, $"{indent}    {target} = buf[offset..offset+slen as usize].to_vec();");
            }
            AppendInvariant(sb, $"{indent}    offset += slen as usize;");
            AppendInvariant(sb, $"{indent}}}");
        }
        else if (field.RustType.StartsWith("Vec<", StringComparison.Ordinal))
        {
            string elemType = field.RustType.Substring(4, field.RustType.Length - 5);
            AppendInvariant(sb, $"{indent}let cnt = i32::from_le_bytes(buf[offset..offset+4].try_into().unwrap());");
            AppendInvariant(sb, $"{indent}offset += 4;");
            if (field.IsNullable)
            {
                AppendInvariant(sb, $"{indent}let mut val = Vec::new();");
            }
            AppendInvariant(sb, $"{indent}if cnt > 0 {{");
            AppendInvariant(sb, $"{indent}    let elem_count = cnt as usize;");
            AppendInvariant(sb, $"{indent}    let elem_size = std::mem::size_of::<{elemType}>();");
            AppendInvariant(sb, $"{indent}    if offset + (elem_count * elem_size) > buf.len() {{ return Err(()); }}");
            if (field.IsNullable)
            {
                AppendInvariant(sb, $"{indent}    val.reserve(elem_count);");
            }
            else
            {
                AppendInvariant(sb, $"{indent}    {obj}.{snake}.reserve(elem_count);");
            }
            AppendInvariant(sb, $"{indent}    for _ in 0..elem_count {{");
            AppendInvariant(sb, $"{indent}        let item = {elemType}::from_le_bytes(buf[offset..offset+elem_size].try_into().unwrap());");
            AppendInvariant(sb, $"{indent}        offset += elem_size;");
            if (field.IsNullable)
            {
                AppendInvariant(sb, $"{indent}        val.push(item);");
            }
            else
            {
                AppendInvariant(sb, $"{indent}        {obj}.{snake}.push(item);");
            }
            AppendInvariant(sb, $"{indent}    }}");
            AppendInvariant(sb, $"{indent}}}");
        }
        else if (size == 1)
        {
            AppendInvariant(sb, $"{indent}{target} = buf[offset] as {field.RustType};");
            AppendInvariant(sb, $"{indent}offset += 1;");
        }
        else if (size == 2)
        {
            AppendInvariant(sb, $"{indent}{target} = {field.RustType}::from_le_bytes([buf[offset], buf[offset+1]]);");
            AppendInvariant(sb, $"{indent}offset += 2;");
        }
        else if (size == 4)
        {
            AppendInvariant(sb, $"{indent}{target} = {field.RustType}::from_le_bytes(buf[offset..offset+4].try_into().unwrap());");
            AppendInvariant(sb, $"{indent}offset += 4;");
        }
        else if (size == 8)
        {
            AppendInvariant(sb, $"{indent}{target} = {field.RustType}::from_le_bytes(buf[offset..offset+8].try_into().unwrap());");
            AppendInvariant(sb, $"{indent}offset += 8;");
        }

        if (field.IsNullable)
        {
            AppendInvariant(sb, $"{indent}{obj}.{snake} = Some(val);");
            indent = indent.Substring(0, indent.Length - 4);
            AppendInvariant(sb, $"{indent}}} else {{");
            AppendInvariant(sb, $"{indent}    {obj}.{snake} = None;");
            AppendInvariant(sb, $"{indent}    offset += 1;");
            AppendInvariant(sb, $"{indent}}}");
        }
    }

    private static string GenerateTests(IReadOnlyList<PacketSchema> packets)
    {
        StringBuilder sb = new(32768);

        _ = sb.AppendLine("// <auto-generated/>");
        _ = sb.AppendLine("// Round-trip serialization tests for Nalix packets");
        _ = sb.AppendLine();
        _ = sb.AppendLine("use super::*;");
        _ = sb.AppendLine();

        foreach (PacketSchema packet in packets)
        {
            string name = packet.Name;
            string snake = ToSnakeCase(name);

            _ = sb.AppendLine("#[test]");
            AppendInvariant(sb, $"fn {snake}_round_trip() {{");
            AppendInvariant(sb, $"    let mut pkt = {name}::default();");

            int fieldIdx = 0;
            foreach (FieldSchema f in packet.Fields)
            {
                if (f.IsHeader)
                {
                    continue;
                }
                string fsnake = ToSnakeCase(f.Name);
                string testValue = GetTestValue(f, fieldIdx);
                AppendInvariant(sb, $"    pkt.{fsnake} = {testValue};");
                fieldIdx++;
            }

            _ = sb.AppendLine();
            if (packet.HasVariableFields)
            {
                AppendInvariant(sb, $"    let mut buf = vec![0u8; {name}::FIXED_SIZE + 1024];");
                AppendInvariant(sb, $"    let written = pkt.serialize(&mut buf).expect(\"serialize failed\");");
                AppendInvariant(sb, $"    let parsed = {name}::deserialize(&buf[..written]).expect(\"deserialize failed\");");
                _ = sb.AppendLine("    assert_eq!(pkt, parsed);");
            }
            else
            {
                AppendInvariant(sb, $"    let mut buf = [0u8; {name}::FIXED_SIZE];");
                AppendInvariant(sb, $"    let written = pkt.serialize(&mut buf).expect(\"serialize failed\");");
                AppendInvariant(sb, $"    assert_eq!(written, {name}::FIXED_SIZE);");
                _ = sb.AppendLine();
                AppendInvariant(sb, $"    let parsed = {name}::deserialize(&buf).expect(\"deserialize failed\");");
                _ = sb.AppendLine("    assert_eq!(pkt, parsed);");
            }
            _ = sb.AppendLine("}");
            _ = sb.AppendLine();
        }

        _ = sb.AppendLine("#[test]");
        _ = sb.AppendLine("fn verify_sizes() {");
        foreach (PacketSchema packet in packets)
        {
            int fixedSize = CalculateFixedSize(packet);
            AppendInvariant(sb, $"    assert_eq!({packet.Name}::FIXED_SIZE, {fixedSize});");
        }
        _ = sb.AppendLine("}");

        return sb.ToString();
    }

    private static string GetTestValue(FieldSchema field, int index)
    {
        string rustType = field.RustType;
        string val = "";

        if (rustType == "Vec<Vec<u8>>" || rustType.StartsWith("Vec<", StringComparison.Ordinal))
        {
            val = "vec![]";
        }
        else if (rustType.StartsWith("[u8; ", StringComparison.Ordinal))
        {
            val = FormattableString.Invariant($"[0x{index + 1:X2}u8; {field.Size}]");
        }
        else if (rustType is "u128" or "i128")
        {
            val = FormattableString.Invariant($"0x{index + 100000:X}{rustType}");
        }
        else if (rustType == ProtocolConstants.PacketHeaderName)
        {
            val = "PacketHeader::default()";
        }
        else
        {
            val = rustType switch
            {
                "u8" => FormattableString.Invariant($"0x{index + 1:X2}u8"),
                "i8" => FormattableString.Invariant($"0x{index + 1:X2}i8"),
                "u16" => FormattableString.Invariant($"0x{index + 100:X4}u16"),
                "i16" => FormattableString.Invariant($"0x{index + 100:X4}i16"),
                "u32" => FormattableString.Invariant($"0x{index + 1000:X8}u32"),
                "i32" => FormattableString.Invariant($"0x{index + 1000:X8}i32"),
                "u64" => FormattableString.Invariant($"0x{index + 10000:X16}u64"),
                "i64" => FormattableString.Invariant($"0x{index + 10000:X16}i64"),
                "f32" => FormattableString.Invariant($"{index + 1.0f}f32"),
                "f64" => FormattableString.Invariant($"{index + 1.0}f64"),
                _ => "0"
            };
        }

        return field.IsNullable ? $"Some({val})" : val;
    }

    private static readonly HashSet<string> s_rustKeywords = new(StringComparer.Ordinal)
    {
        "as", "break", "const", "continue", "crate", "else", "enum", "extern", "false", "fn", "for",
        "if", "impl", "in", "let", "loop", "match", "mod", "move", "mut", "pub", "ref", "return",
        "self", "Self", "static", "struct", "super", "trait", "true", "type", "unsafe", "use",
        "where", "while", "async", "await", "dyn", "abstract", "become", "box", "do", "final",
        "macro", "override", "priv", "typeof", "unsized", "virtual", "yield", "try"
    };

    private static string ToSnakeCase(string name)
    {
        if (string.IsNullOrEmpty(name))
        {
            return name;
        }

        StringBuilder sb = new(name.Length + 4);
        for (int i = 0; i < name.Length; i++)
        {
            char c = name[i];
            if (char.IsUpper(c) && i > 0)
            {
                _ = sb.Append('_');
            }
            _ = sb.Append(char.ToLowerInvariant(c));
        }

        string result = sb.ToString();
        return s_rustKeywords.Contains(result) ? $"r#{result}" : result;
    }

    private static void AppendInvariant(StringBuilder sb, FormattableString value) => sb.AppendLine(FormattableString.Invariant(value));
