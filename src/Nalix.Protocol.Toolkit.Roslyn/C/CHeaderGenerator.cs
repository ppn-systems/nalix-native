using System.Text;
using Nalix.Protocol.Toolkit.Abstractions;

namespace Nalix.Protocol.Toolkit.Roslyn.C;

/// <summary>
/// Generates native C header and source files for Nalix protocol frames.
/// Clean naming: struct = Handshake, function = handshake_serialize.
/// No nalix_ prefix, no _t suffix.
/// </summary>
public sealed class CHeaderGenerator : GeneratorBase
{
    /// <inheritdoc/>
    protected override void GenerateFiles(
        IReadOnlyList<PacketDefinition> allPackets,
        IReadOnlyList<PacketDefinition> nonHeaderPackets,
        List<GeneratedFile> files)
    {
        string header = GenerateHeader(allPackets, nonHeaderPackets);
        string source = GenerateSource(nonHeaderPackets);
        string tests = GenerateTests(nonHeaderPackets);

        files.Add(new GeneratedFile("packets.h", header, "include/"));
        files.Add(new GeneratedFile("packets.c", source, "src/"));
        files.Add(new GeneratedFile("packet_test.c", tests, "tests/"));
    }

    private static string GenerateHeader(
        IReadOnlyList<PacketDefinition> allPackets,
        IReadOnlyList<PacketDefinition> nonHeaderPackets)
    {
        StringBuilder sb = new(32768);

        _ = sb.AppendLine("// <auto-generated/>");
        _ = sb.AppendLine("// Generated by Nalix.Protocol.Toolkit — CHeaderGenerator");
        _ = sb.AppendLine("// DO NOT EDIT MANUALLY");
        _ = sb.AppendLine();
        _ = sb.AppendLine("#pragma once");
        _ = sb.AppendLine();
        _ = sb.AppendLine("#include <stdint.h>");
        _ = sb.AppendLine("#include <stddef.h>");
        _ = sb.AppendLine("#include <stdbool.h>");
        _ = sb.AppendLine("#include <string.h>");
        _ = sb.AppendLine();

        _ = sb.AppendLine("typedef struct { uint8_t data[32]; } Bytes32;");
        _ = sb.AppendLine();
        _ = sb.AppendLine("// Length-prefixed UTF-8 string (matches Nalix codec wire format)");
        _ = sb.AppendLine("// null = length -1, empty = length 0, otherwise [int32_t length][utf8 bytes]");
        _ = sb.AppendLine("typedef struct { int32_t length; uint8_t* data; } NalixString;");
        _ = sb.AppendLine("void nalix_string_free(NalixString* s);");
        _ = sb.AppendLine();
        _ = sb.AppendLine("#define PACKET_HEADER_SIZE 10");
        _ = sb.AppendLine();

        PacketDefinition? headerPacket = allPackets.FirstOrDefault(p => p.Name == "PacketHeader");
        if (headerPacket != null)
        {
            _ = sb.AppendLine("#if defined(_MSC_VER)");
            _ = sb.AppendLine("    #pragma pack(push, 1)");
            _ = sb.AppendLine("#endif");
            _ = sb.AppendLine();
            _ = sb.AppendLine("typedef struct {");
            foreach (PacketField f in headerPacket.Fields)
            {
                AppendInvariant(sb, $"    {f.CType} {f.Name};");
            }
            _ = sb.AppendLine("} PacketHeader;");
            _ = sb.AppendLine();
            _ = sb.AppendLine("#if defined(_MSC_VER)");
            _ = sb.AppendLine("    #pragma pack(pop)");
            _ = sb.AppendLine("#endif");
            _ = sb.AppendLine();
        }

        foreach (PacketDefinition p in nonHeaderPackets)
        {
            int wireSize = CalculateWireSize(p);

            AppendInvariant(sb, $"// {p.Name} — {wireSize} bytes, magic 0x{p.Magic:X8}");
            AppendInvariant(sb, $"#define PACKET_{p.Name.ToUpperInvariant()} 0x{p.Magic:X8}U");
            AppendInvariant(sb, $"#define {p.Name.ToUpperInvariant()}_SIZE {wireSize}");
            _ = sb.AppendLine();
            _ = sb.AppendLine("#if defined(_MSC_VER)");
            _ = sb.AppendLine("    #pragma pack(push, 1)");
            _ = sb.AppendLine("#endif");
            _ = sb.AppendLine();
            _ = sb.AppendLine("typedef struct {");
            foreach (PacketField f in p.Fields)
            {
                string cType = f.CSharpType.Contains("PacketHeader", StringComparison.Ordinal) ? "PacketHeader" : f.CType;
                AppendInvariant(sb, $"    {cType} {f.Name};");
            }
            AppendInvariant(sb, $"}} {p.Name};");
            _ = sb.AppendLine();
            _ = sb.AppendLine("#if defined(_MSC_VER)");
            _ = sb.AppendLine("    #pragma pack(pop)");
            _ = sb.AppendLine("#endif");
            _ = sb.AppendLine();

            string lower = p.Name.ToLowerInvariant();
            AppendInvariant(sb, $"size_t {lower}_serialize(const {p.Name}* pkt, uint8_t* buf, size_t buf_size);");
            AppendInvariant(sb, $"size_t {lower}_deserialize({p.Name}* pkt, const uint8_t* buf, size_t buf_size);");
            AppendInvariant(sb, $"bool {lower}_equals(const {p.Name}* a, const {p.Name}* b);");
            _ = sb.AppendLine();
        }

        return sb.ToString();
    }

    private static string GenerateSource(IReadOnlyList<PacketDefinition> nonHeaderPackets)
    {
        StringBuilder sb = new(65536);

        _ = sb.AppendLine("// <auto-generated/>");
        _ = sb.AppendLine("#include \"packets.h\"");
        _ = sb.AppendLine("#include <stdlib.h>");
        _ = sb.AppendLine();

        // nalix_string_free helper
        _ = sb.AppendLine("void nalix_string_free(NalixString* s) {");
        _ = sb.AppendLine("    if (s && s->data) { free(s->data); s->data = NULL; s->length = 0; }");
        _ = sb.AppendLine("}");
        _ = sb.AppendLine();

        foreach (PacketDefinition p in nonHeaderPackets)
        {
            string name = p.Name;
            string lower = name.ToLowerInvariant();
            bool hasString = p.Fields.Any(f => f.CType == "NalixString");
            int fixedSize = CalculateFixedSize(p);

            if (hasString)
            {
                // Variable-size serialize
                AppendInvariant(sb, $"size_t {lower}_serialize(const {name}* pkt, uint8_t* buf, size_t buf_size)");
                _ = sb.AppendLine("{");
                AppendInvariant(sb, $"    if (!pkt || !buf) return 0;");
                AppendInvariant(sb, $"    size_t min_size = {fixedSize};");
                _ = sb.AppendLine("    uint8_t* ptr = buf;");
                _ = sb.AppendLine();
                foreach (PacketField field in p.Fields)
                {
                    WriteSerializeField(sb, field);
                }
                _ = sb.AppendLine("    return (size_t)(ptr - buf);");
                _ = sb.AppendLine("}");
                _ = sb.AppendLine();

                // Variable-size deserialize
                AppendInvariant(sb, $"size_t {lower}_deserialize({name}* pkt, const uint8_t* buf, size_t buf_size)");
                _ = sb.AppendLine("{");
                AppendInvariant(sb, $"    if (!pkt || !buf || buf_size < {fixedSize}) return 0;");
                _ = sb.AppendLine("    const uint8_t* ptr = buf;");
                _ = sb.AppendLine();
                foreach (PacketField field in p.Fields)
                {
                    WriteDeserializeField(sb, field);
                }
                _ = sb.AppendLine("    return (size_t)(ptr - buf);");
                _ = sb.AppendLine("}");
                _ = sb.AppendLine();

                // Field-by-field equals for string packets
                AppendInvariant(sb, $"bool {lower}_equals(const {name}* a, const {name}* b)");
                _ = sb.AppendLine("{");
                _ = sb.AppendLine("    if (!a || !b) return false;");
                foreach (PacketField field in p.Fields)
                {
                    WriteEqualsField(sb, field, name);
                }
                _ = sb.AppendLine("    return true;");
                _ = sb.AppendLine("}");
                _ = sb.AppendLine();

                // Free function for string packets
                AppendInvariant(sb, $"void {lower}_free({name}* pkt)");
                _ = sb.AppendLine("{");
                _ = sb.AppendLine("    if (!pkt) return;");
                foreach (PacketField field in p.Fields)
                {
                    if (field.CType == "NalixString")
                    {
                        AppendInvariant(sb, $"    nalix_string_free(&pkt->{field.Name});");
                    }
                }
                _ = sb.AppendLine("}");
                _ = sb.AppendLine();
            }
            else
            {
                // Fixed-size serialize
                AppendInvariant(sb, $"size_t {lower}_serialize(const {name}* pkt, uint8_t* buf, size_t buf_size)");
                _ = sb.AppendLine("{");
                AppendInvariant(sb, $"    if (!pkt || !buf || buf_size < {fixedSize}) return 0;");
                _ = sb.AppendLine("    uint8_t* ptr = buf;");
                _ = sb.AppendLine();
                foreach (PacketField field in p.Fields)
                {
                    WriteSerializeField(sb, field);
                }
                AppendInvariant(sb, $"    return {fixedSize};");
                _ = sb.AppendLine("}");
                _ = sb.AppendLine();

                // Fixed-size deserialize
                AppendInvariant(sb, $"size_t {lower}_deserialize({name}* pkt, const uint8_t* buf, size_t buf_size)");
                _ = sb.AppendLine("{");
                AppendInvariant(sb, $"    if (!pkt || !buf || buf_size < {fixedSize}) return 0;");
                _ = sb.AppendLine("    const uint8_t* ptr = buf;");
                _ = sb.AppendLine();
                foreach (PacketField field in p.Fields)
                {
                    WriteDeserializeField(sb, field);
                }
                AppendInvariant(sb, $"    return {fixedSize};");
                _ = sb.AppendLine("}");
                _ = sb.AppendLine();

                // memcmp equals for fixed-size
                AppendInvariant(sb, $"bool {lower}_equals(const {name}* a, const {name}* b)");
                _ = sb.AppendLine("{");
                _ = sb.AppendLine("    if (!a || !b) return false;");
                AppendInvariant(sb, $"    return memcmp(a, b, sizeof({name})) == 0;");
                _ = sb.AppendLine("}");
                _ = sb.AppendLine();
            }
        }

        return sb.ToString();
    }

    private static void WriteSerializeField(StringBuilder sb, PacketField field)
    {
        string cs = field.CSharpType;
        string name = field.Name;
        int size = GetFieldSize(field);

        if (cs.Contains("PacketHeader", StringComparison.Ordinal))
        {
            AppendInvariant(sb, $"    memcpy(ptr, &pkt->{name}, PACKET_HEADER_SIZE); ptr += PACKET_HEADER_SIZE;");
        }
        else if (cs == "Nalix.Abstractions.Primitives.Bytes32")
        {
            AppendInvariant(sb, $"    memcpy(ptr, pkt->{name}.data, 32); ptr += 32;");
        }
        else if (field.CType == "NalixString")
        {
            // Length-prefixed UTF-8: [int32_t length][bytes]
            _ = sb.AppendLine("    {");
            AppendInvariant(sb, $"        int32_t slen = pkt->{name}.length;");
            _ = sb.AppendLine("        memcpy(ptr, &slen, 4); ptr += 4;");
            AppendInvariant(sb, $"        if (slen > 0 && pkt->{name}.data) {{ memcpy(ptr, pkt->{name}.data, slen); ptr += slen; }}");
            _ = sb.AppendLine("    }");
        }
        else if (size == 1)
        {
            AppendInvariant(sb, $"    ptr[0] = (uint8_t)pkt->{name}; ptr += 1;");
        }
        else if (size == 2)
        {
            AppendInvariant(sb, $"    ptr[0] = (uint8_t)(pkt->{name});");
            AppendInvariant(sb, $"    ptr[1] = (uint8_t)((pkt->{name}) >> 8); ptr += 2;");
        }
        else if (size == 4)
        {
            AppendInvariant(sb, $"    ptr[0] = (uint8_t)(pkt->{name});");
            AppendInvariant(sb, $"    ptr[1] = (uint8_t)((pkt->{name}) >> 8);");
            AppendInvariant(sb, $"    ptr[2] = (uint8_t)((pkt->{name}) >> 16);");
            AppendInvariant(sb, $"    ptr[3] = (uint8_t)((pkt->{name}) >> 24); ptr += 4;");
        }
        else if (size == 8)
        {
            AppendInvariant(sb, $"    ptr[0] = (uint8_t)(pkt->{name});");
            AppendInvariant(sb, $"    ptr[1] = (uint8_t)((pkt->{name}) >> 8);");
            AppendInvariant(sb, $"    ptr[2] = (uint8_t)((pkt->{name}) >> 16);");
            AppendInvariant(sb, $"    ptr[3] = (uint8_t)((pkt->{name}) >> 24);");
            AppendInvariant(sb, $"    ptr[4] = (uint8_t)((pkt->{name}) >> 32);");
            AppendInvariant(sb, $"    ptr[5] = (uint8_t)((pkt->{name}) >> 40);");
            AppendInvariant(sb, $"    ptr[6] = (uint8_t)((pkt->{name}) >> 48);");
            AppendInvariant(sb, $"    ptr[7] = (uint8_t)((pkt->{name}) >> 56); ptr += 8;");
        }
    }

    private static void WriteDeserializeField(StringBuilder sb, PacketField field)
    {
        string cs = field.CSharpType;
        string name = field.Name;
        int size = GetFieldSize(field);

        if (cs.Contains("PacketHeader", StringComparison.Ordinal))
        {
            AppendInvariant(sb, $"    memcpy(&pkt->{name}, ptr, PACKET_HEADER_SIZE); ptr += PACKET_HEADER_SIZE;");
        }
        else if (cs == "Nalix.Abstractions.Primitives.Bytes32")
        {
            AppendInvariant(sb, $"    memcpy(pkt->{name}.data, ptr, 32); ptr += 32;");
        }
        else if (field.CType == "NalixString")
        {
            // Length-prefixed UTF-8: read length, bounds check, then allocate and copy
            _ = sb.AppendLine("    {");
            _ = sb.AppendLine("        int32_t slen;");
            _ = sb.AppendLine("        memcpy(&slen, ptr, 4); ptr += 4;");
            AppendInvariant(sb, $"        pkt->{name}.length = slen;");
            AppendInvariant(sb, $"        if (slen > 0) {{");
            _ = sb.AppendLine("            if ((size_t)(ptr - buf) + slen > buf_size) return 0;");
            AppendInvariant(sb, $"            pkt->{name}.data = (uint8_t*)malloc(slen);");
            AppendInvariant(sb, $"            memcpy(pkt->{name}.data, ptr, slen);");
            _ = sb.AppendLine("            ptr += slen;");
            _ = sb.AppendLine("        } else {");
            AppendInvariant(sb, $"            pkt->{name}.data = NULL;");
            _ = sb.AppendLine("        }");
            _ = sb.AppendLine("    }");
        }
        else if (size == 1)
        {
            AppendInvariant(sb, $"    pkt->{name} = ({field.CType})ptr[0]; ptr += 1;");
        }
        else if (size == 2)
        {
            AppendInvariant(sb, $"    pkt->{name} = ({field.CType})((uint16_t)ptr[0] | ((uint16_t)ptr[1] << 8)); ptr += 2;");
        }
        else if (size == 4)
        {
            AppendInvariant(sb, $"    pkt->{name} = ({field.CType})((uint32_t)ptr[0] | ((uint32_t)ptr[1] << 8) | ((uint32_t)ptr[2] << 16) | ((uint32_t)ptr[3] << 24)); ptr += 4;");
        }
        else if (size == 8)
        {
            AppendInvariant(sb, $"    pkt->{name} = ({field.CType})((uint64_t)ptr[0] | ((uint64_t)ptr[1] << 8) | ((uint64_t)ptr[2] << 16) | ((uint64_t)ptr[3] << 24) | ((uint64_t)ptr[4] << 32) | ((uint64_t)ptr[5] << 40) | ((uint64_t)ptr[6] << 48) | ((uint64_t)ptr[7] << 56)); ptr += 8;");
        }
    }

    private static void WriteEqualsField(StringBuilder sb, PacketField field, string structName)
    {
        string name = field.Name;

        if (field.CType == "NalixString")
        {
            AppendInvariant(sb, $"    if (a->{name}.length != b->{name}.length) return false;");
            AppendInvariant(sb, $"    if (a->{name}.length > 0 && memcmp(a->{name}.data, b->{name}.data, a->{name}.length) != 0) return false;");
        }
        else if (field.CSharpType.Contains("PacketHeader", StringComparison.Ordinal))
        {
            AppendInvariant(sb, $"    if (memcmp(&a->{name}, &b->{name}, PACKET_HEADER_SIZE) != 0) return false;");
        }
        else
        {
            int size = GetFieldSize(field);
            AppendInvariant(sb, $"    if (memcmp(&a->{name}, &b->{name}, {size}) != 0) return false;");
        }
    }

    private static int CalculateFixedSize(PacketDefinition packet)
    {
        int size = 0;
        foreach (PacketField f in packet.Fields)
        {
            if (f.CType == "NalixString")
            {
                size += 4; // length prefix only
            }
            else
            {
                size += GetFieldSize(f);
            }
        }
        return size;
    }

    private static string GenerateTests(IReadOnlyList<PacketDefinition> packets)
    {
        StringBuilder sb = new(32768);

        _ = sb.AppendLine("// <auto-generated/>");
        _ = sb.AppendLine("// Compile: gcc -I../include -o packet_test packet_test.c && ./packet_test");
        _ = sb.AppendLine();
        _ = sb.AppendLine("#include \"packets.h\"");
        _ = sb.AppendLine("#include <stdio.h>");
        _ = sb.AppendLine("#include <string.h>");
        _ = sb.AppendLine("#include <assert.h>");
        _ = sb.AppendLine();

        foreach (PacketDefinition p in packets)
        {
            string lower = p.Name.ToLowerInvariant();
            int wireSize = CalculateWireSize(p);

            AppendInvariant(sb, $"static void test_{lower}_round_trip(void)");
            _ = sb.AppendLine("{");
            AppendInvariant(sb, $"    {p.Name} pkt;");
            _ = sb.AppendLine("    memset(&pkt, 0, sizeof(pkt));");
            int fieldIdx = 0;
            foreach (PacketField f in p.Fields)
            {
                string cv = GetCTestValue(f, fieldIdx);
                if (f.CSharpType.Contains("PacketHeader", StringComparison.Ordinal))
                {
                    AppendInvariant(sb, $"    memset(&pkt.{f.Name}, 0, sizeof(PacketHeader));");
                }
                else if (cv.StartsWith('{'))
                {
                    AppendInvariant(sb, $"    {{ {f.CType} tmp = {cv}; pkt.{f.Name} = tmp; }}");
                }
                else
                {
                    AppendInvariant(sb, $"    pkt.{f.Name} = {cv};");
                }
                fieldIdx++;
            }
            _ = sb.AppendLine();
            AppendInvariant(sb, $"    uint8_t buf[{p.Name.ToUpperInvariant()}_SIZE];");
            AppendInvariant(sb, $"    size_t written = {lower}_serialize(&pkt, buf, sizeof(buf));");
            AppendInvariant(sb, $"    assert(written == {wireSize});");
            _ = sb.AppendLine();
            AppendInvariant(sb, $"    {p.Name} parsed;");
            _ = sb.AppendLine("    memset(&parsed, 0, sizeof(parsed));");
            AppendInvariant(sb, $"    size_t rd = {lower}_deserialize(&parsed, buf, sizeof(buf));");
            AppendInvariant(sb, $"    assert(rd == {wireSize});");
            AppendInvariant(sb, $"    assert({lower}_equals(&pkt, &parsed));");
            AppendInvariant(sb, $"    printf(\"  [PASS] {p.Name} round-trip\\n\");");
            _ = sb.AppendLine("}");
            _ = sb.AppendLine();
        }

        _ = sb.AppendLine("int main(void)");
        _ = sb.AppendLine("{");
        _ = sb.AppendLine("    printf(\"Nalix Protocol Round-trip Tests\\n\\n\");");
        foreach (PacketDefinition p in packets)
        {
            AppendInvariant(sb, $"    test_{p.Name.ToLowerInvariant()}_round_trip();");
        }
        _ = sb.AppendLine("    printf(\"\\nAll tests passed!\\n\");");
        _ = sb.AppendLine("    return 0;");
        _ = sb.AppendLine("}");

        return sb.ToString();
    }

    private static string GetCTestValue(PacketField field, int index)
    {
        string cs = field.CSharpType;
        int size = GetFieldSize(field);

        if (cs.Contains("PacketHeader", StringComparison.Ordinal))
        {
            return "{0}";
        }

        if (cs == "Nalix.Abstractions.Primitives.Bytes32")
        {
            return $"{{{{ 0x{index + 1:X2} }}}}";
        }

        return size switch
        {
            1 => FormattableString.Invariant($"0x{index + 1:X2}"),
            2 => FormattableString.Invariant($"0x{index + 100:X4}"),
            4 => FormattableString.Invariant($"0x{index + 1000:X8}"),
            8 => FormattableString.Invariant($"0x{index + 10000:X16}ULL"),
            _ => "0"
        };
    }

    private static void AppendInvariant(StringBuilder sb, FormattableString value) => sb.AppendLine(FormattableString.Invariant(value));
}
